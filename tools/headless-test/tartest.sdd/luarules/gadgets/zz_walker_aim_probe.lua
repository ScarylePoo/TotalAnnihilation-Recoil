function gadget:GetInfo()
  return { name = "Walker Aim Probe", layer = 1003, enabled = true }
end

-- Do armed units fire and hit, and do their guns follow the target up and down? Runs alone (AIM=1 run.sh): one immune copy of every armed unit (land units
-- and buildings on land, ships, subs and sea buildings in a lake on the map's east side, aircraft on land), each with its own immune enemy (a Peewee, a
-- Skeeter in the lake, a circling Peeper for AA-only weapons), gets a far ground attack, a near ground attack on the other side, an
-- attack order on the enemy, then fire-at-will with the enemy walking across. Stockpile and manual-fire weapons are left to zz_script_probe. Per weapon, using the piece script.QueryWeapon returns and its ancestor
-- at least 4 elmos away (the "barrel"), logs [HARNESS] waim: shots and hits per phase; barrel and target pitch/yaw at the end of the far and near phases;
-- "follow" = change in barrel pitch over change in target pitch (1 = follows, 0 = the gun ignores pitch).
-- Runs on COB units too (no script environment there, so shots and hits only). POSE lines give every piece's matrix at the end of the far and near phases,
-- so tools/s3okit/kit/compare_probe.py can diff a COB run against a Lua run.
-- Flags: NOFIRE, NOHIT (fires but never damages the enemy), NOPITCH (direct-fire weapon, not an aircraft, follow < 0.4), OFFAXIS (barrel > 25 deg off target at the end of a ground attack).
-- A fifth phase walks the unit across while it fires at will. The barrel is the first ancestor with geometry -> muzzle, from luarules/aim_axes.lua
-- (generated by tools/s3okit/kit/make_aim_axes.py: gun geometry centre to muzzle), so odd pivots do not matter. Rockets legitimately read as off axis.
if not gadgetHandler:IsSyncedCode() or not (Spring.GetModOptions() or {}).aimonly or (Spring.GetModOptions() or {}).scriptonly or (Spring.GetModOptions() or {}).waterprobe then return end

local units = {}
local protected = {}
local byUid = {}
local curPhase = 1
function gadget:UnitPreDamaged(uid, _, _, damage, _, weaponDefID, _, attacker)
  local s = attacker and byUid[attacker]
  if s and weaponDefID and s.byDef[weaponDefID] and damage > 0 then
    local rec = s.byDef[weaponDefID]
    rec.hits[curPhase] = rec.hits[curPhase] + 1
  end
  if protected[uid] then return 0, 0 end
end

local function log(...) Spring.Echo("[HARNESS] waim", ...) end

local SIZE = Game.mapSizeX
local LAKE_X0, LAKE_X1 = SIZE * 0.55, SIZE * 0.97
local DIRECT = {Cannon = true, LaserCannon = true, BeamLaser = true, EmgCannon = true, Flame = true, LightningCannon = true, DGun = true}

function gadget:Initialize()
  Spring.SetHeightMapFunc(function()
    for x = 0, SIZE, 8 do
      for z = 0, Game.mapSizeZ, 8 do
        if x > LAKE_X0 and x < LAKE_X1 then Spring.SetHeightMap(x, z, -60) end
      end
    end
  end)
end

local function isWaterUnit(ud)
  if ud.minWaterDepth and ud.minWaterDepth > 0 then return true end
  local md = ud.moveDef
  local n = md and md.name and md.name:lower() or ""
  return n:find("ship") ~= nil or n:find("boat") ~= nil or n:find("sub") ~= nil
end

local function logPose(s, tag)
  local names = Spring.GetUnitPieceList(s.uid)
  if not names then return end
  local parts = {}
  for i, n in ipairs(names) do
    local m = {Spring.GetUnitPieceMatrix(s.uid, i)}
    parts[#parts + 1] = string.format("%s=%.2f,%.2f,%.2f,%.2f,%.2f,%.2f,%.2f,%.2f,%.2f,%.1f,%.1f,%.1f", n, m[1], m[2], m[3], m[5], m[6], m[7], m[9], m[10], m[11], m[13], m[14], m[15])
  end
  Spring.Echo("[POSE] " .. s.name .. " " .. tag .. " " .. table.concat(parts, " "))
end

local function pieceWorld(uid, p)
  local x, y, z = Spring.GetUnitPiecePosition(uid, p)
  local bx, by, bz = Spring.GetUnitBasePosition(uid)
  local f, u, r = Spring.GetUnitVectors(uid)
  return bx + r[1] * x + u[1] * y + f[1] * z, by + r[2] * x + u[2] * y + f[2] * z, bz + r[3] * x + u[3] * y + f[3] * z
end

local AXES = VFS.Include("luarules/aim_axes.lua")

local function toWorld(uid, x, y, z)
  local f, u, r = Spring.GetUnitVectors(uid)
  return r[1] * x + u[1] * y + f[1] * z, r[2] * x + u[2] * y + f[2] * z, r[3] * x + u[3] * y + f[3] * z
end

local function sample(s, w, tag, tx, tz)
  local env = Spring.UnitScript.GetScriptEnv(s.uid)
  local rec = s.w[w]
  if not env then rec[tag] = false ; return end       -- a COB unit
  local ok, q = pcall(Spring.UnitScript.CallAsUnit, s.uid, env.script.QueryWeapon, w)
  if not ok or not q or q < 1 then rec[tag] = false ; return end
  local qn = Spring.GetUnitPieceList(s.uid)[q]
  local ax = AXES[s.name] and AXES[s.name][qn]
  if not ax then rec[tag] = false ; return end
  local anc = s.map[ax[1]]
  local m = {Spring.GetUnitPieceMatrix(s.uid, anc)}
  -- the matrix's x is model x, GetUnitPiecePosition's is mirrored: find out from the known offset ancestor -> muzzle
  local function mul(x, y, z) return m[1]*x + m[5]*y + m[9]*z, m[2]*x + m[6]*y + m[10]*z, m[3]*x + m[7]*y + m[11]*z end
  local ox, oy, oz = mul(ax[5], ax[6], ax[7])
  local qx, qy, qz = Spring.GetUnitPiecePosition(s.uid, q)
  local px, py, pz = Spring.GetUnitPiecePosition(s.uid, anc)
  local flip = ((qx - px) * ox < 0) and -1 or 1
  local dx, dy, dz = mul(ax[2], ax[3], ax[4])
  dx, dy, dz = toWorld(s.uid, flip * dx, dy, dz)
  local mx, my, mz = pieceWorld(s.uid, q)
  local ty = Spring.GetGroundHeight(tx, tz)
  local vx, vy, vz = tx - mx, ty - my, tz - mz
  local dl, vl = math.sqrt(dx*dx + dy*dy + dz*dz), math.sqrt(vx*vx + vy*vy + vz*vz)
  rec.names = ax[1] .. ">" .. qn
  rec[tag] = {
    pitch = math.deg(math.asin(dy / dl)), tp = math.deg(math.asin(vy / vl)),
    yaw = math.deg(math.atan2(dx, dz)), ty = math.deg(math.atan2(vx, vz)),
    off = math.deg(math.acos(math.max(-1, math.min(1, (dx*vx + dy*vy + dz*vz) / (dl * vl))))),
  }
end

local function report(s)
  for w, rec in pairs(s.w) do
    local f, n = rec.far, rec.near
    local sh, hi = rec.shots, rec.hits
    local shots = string.format("shots %d/%d/%d/%d/%d hits %d/%d/%d/%d/%d", sh[1], sh[2], sh[3], sh[4], sh[5], hi[1], hi[2], hi[3], hi[4], hi[5])
    local flags = {}
    if sh[1] + sh[2] + sh[3] + sh[4] + sh[5] == 0 then flags[#flags + 1] = "NOFIRE"
    elseif hi[3] + hi[4] + hi[5] == 0 then flags[#flags + 1] = "NOHIT" end
    if f and n then
      local follow = (n.pitch - f.pitch) / (n.tp - f.tp)
      if rec.direct and not s.air and math.abs(follow) < 0.4 then flags[#flags + 1] = "NOPITCH" end
      if not s.air and (f.off > 25 or n.off > 25) then flags[#flags + 1] = "OFFAXIS" end
      log(s.name, "w" .. w, rec.wname, rec.wtype, rec.names, shots, string.format(
        "far barrel %.0f,%.0f target %.0f,%.0f off %.0f; near barrel %.0f,%.0f target %.0f,%.0f off %.0f; follow %.2f; moved %.0f",
        f.pitch, f.yaw, f.tp, f.ty, f.off, n.pitch, n.yaw, n.tp, n.ty, n.off, follow, s.moved or 0),
        #flags > 0 and table.concat(flags, " ") or "ok")
    else
      flags[#flags + 1] = "NOBARREL"
      log(s.name, "w" .. w, rec.wname, rec.wtype, shots, table.concat(flags, " "))
    end
  end
end

local T_SPAWN, T_NEAR, T_UNIT, T_AUTO, T_WALK, T_END = 30, 330, 630, 930, 1230, 1530
local started
function gadget:GameFrame(frame)
  if frame == T_SPAWN then
    started = true
    local landCols, seaCols = math.floor(LAKE_X0 / 700) - 1, math.floor((LAKE_X1 - LAKE_X0) / 700)
    local nLand, nSea = 0, 0
    Spring.SetTeamResource(1, "es", 1e8) ; Spring.SetTeamResource(1, "e", 1e8)
    Spring.SetTeamResource(1, "ms", 1e8) ; Spring.SetTeamResource(1, "m", 1e8)
    Spring.CreateUnit("arm_t1_bot_peewee", 100, 0, Game.mapSizeZ - 100, 0, 0)    -- keeps team 0 alive whatever happens
    local ids = {}
    for id in pairs(UnitDefs) do ids[#ids + 1] = id end
    table.sort(ids)
    for _, id in ipairs(ids) do
      local ud = UnitDefs[id]
      local armed, aaOnly = {}, true
      for w, wd in ipairs(ud.weapons or {}) do
        local def = WeaponDefs[wd.weaponDef]
        if def and def.range and def.range > 0 and def.name ~= "noweapon" and not def.manualFire and not def.stockpile and (def.interceptor or 0) == 0 then
          armed[#armed + 1] = {w, def}
          if not (wd.onlyTargets and wd.onlyTargets.vtol and not wd.onlyTargets.notair) then aaOnly = false end
        end
      end
      if #armed > 0 then
        local sea = isWaterUnit(ud)
        for _, a in ipairs(armed) do
          if ud.canFly and a[2].type == "TorpedoLauncher" then sea = true end     -- torpedo bombers want a ship to hit
        end
        local x, z
        if sea then
          x, z = LAKE_X0 + 400 + (nSea % seaCols) * 700, 400 + math.floor(nSea / seaCols) * 700
          nSea = nSea + 1
        else
          x, z = 400 + (nLand % landCols) * 700, 400 + math.floor(nLand / landCols) * 700
          nLand = nLand + 1
        end
        local uid = Spring.CreateUnit(id, x, Spring.GetGroundHeight(x, z), z, 0, 1)
        if uid then
          local map = Spring.GetUnitPieceMap(uid)
          protected[uid] = true
          Spring.GiveOrderToUnit(uid, CMD.FIRE_STATE, {0}, {})
          local s = {uid = uid, name = ud.name, map = map, x = x, z = z, w = {}, byDef = {}, air = ud.canFly}
          local rmin = math.huge
          for _, a in ipairs(armed) do
            local rec = {wname = a[2].name, wtype = a[2].type, direct = DIRECT[a[2].type], shots = {0, 0, 0, 0, 0}, hits = {0, 0, 0, 0, 0}, last = 0}
            s.w[a[1]] = rec
            s.byDef[a[2].id] = rec
            rmin = math.min(rmin, a[2].range)
          end
          s.far, s.near = math.min(rmin * 0.7, 220), math.max(math.min(rmin * 0.3, 60), 30)
          s.fx, s.fz = x + s.far * 0.5, z + s.far * 0.866
          s.nx, s.nz = x - s.near * 0.5, z + s.near * 0.866
          local tdef = aaOnly and "arm_t1_air_peeper" or (sea and "arm_t1_sea_skeeter" or "arm_t1_bot_peewee")
          s.target = Spring.CreateUnit(tdef, x, Spring.GetGroundHeight(x, z + s.far), z + s.far, 0, 0)
          if s.target then
            protected[s.target] = true
            Spring.GiveOrderToUnit(s.target, CMD.FIRE_STATE, {0}, {})
            if aaOnly then
              Spring.GiveOrderToUnit(s.target, CMD.MOVE, {x + 150, 0, z + 150}, {})
              Spring.GiveOrderToUnit(s.target, CMD.MOVE, {x - 150, 0, z + 150}, {"shift"})
              Spring.GiveOrderToUnit(s.target, CMD.MOVE, {x, 0, z - 150}, {"shift"})
              Spring.GiveOrderToUnit(s.target, CMD.REPEAT, {1}, {})
            end
          end
          byUid[uid] = s
          units[#units + 1] = s
          if aaOnly then
            if s.target then Spring.GiveOrderToUnit(uid, CMD.ATTACK, {s.target}, {}) end
          else
            Spring.GiveOrderToUnit(uid, CMD.ATTACK, {s.fx, Spring.GetGroundHeight(s.fx, s.fz), s.fz}, {})
          end
        else
          log("spawn failed", ud.name)
        end
      end
    end
    log("subjects", #units)
    return
  end
  if not started then return end
  curPhase = (frame <= T_NEAR) and 1 or (frame <= T_UNIT) and 2 or (frame <= T_AUTO) and 3 or (frame <= T_WALK) and 4 or 5
  for _, s in ipairs(units) do
    if Spring.ValidUnitID(s.uid) then
      for w, rec in pairs(s.w) do
        local r = Spring.GetUnitWeaponState(s.uid, w, "reloadFrame")
        if r and r ~= rec.last then
          if r > frame then rec.shots[curPhase] = rec.shots[curPhase] + 1 end
          rec.last = r
        end
      end
      local bx, _, bz = Spring.GetUnitBasePosition(s.uid)
      s.moved = math.max(s.moved or 0, math.sqrt((bx - s.x)^2 + (bz - s.z)^2))
      if frame == T_NEAR then
        for w in pairs(s.w) do sample(s, w, "far", s.fx, s.fz) end
        logPose(s, "far")
        Spring.GiveOrderToUnit(s.uid, CMD.ATTACK, {s.nx, Spring.GetGroundHeight(s.nx, s.nz), s.nz}, {})
      elseif frame == T_UNIT then
        for w in pairs(s.w) do sample(s, w, "near", s.nx, s.nz) end
        logPose(s, "near")
        Spring.GiveOrderToUnit(s.uid, CMD.STOP, {}, {})
        if s.target then Spring.GiveOrderToUnit(s.uid, CMD.ATTACK, {s.target}, {}) end
      elseif frame == T_AUTO then
        Spring.GiveOrderToUnit(s.uid, CMD.STOP, {}, {})
        Spring.GiveOrderToUnit(s.uid, CMD.FIRE_STATE, {2}, {})
        if s.target then
          Spring.GiveOrderToUnit(s.target, CMD.MOVE, {s.x + s.far, 0, s.z + s.far * 0.4}, {})
          Spring.GiveOrderToUnit(s.target, CMD.MOVE, {s.x - s.far, 0, s.z + s.far * 0.4}, {"shift"})
        end
      elseif frame == T_WALK then
        Spring.GiveOrderToUnit(s.uid, CMD.MOVE, {s.x - s.far * 0.8, 0, s.z + s.far * 0.5}, {})
        Spring.GiveOrderToUnit(s.uid, CMD.MOVE, {s.x + s.far * 0.8, 0, s.z + s.far * 0.5}, {"shift"})
      elseif frame == T_END then
        report(s)
      end
    elseif frame == T_END then
      log(s.name, "DIED")
    end
  end
  if frame == T_END + 5 then log("DONE") ; Spring.SendCommands("quitforce") end
end
