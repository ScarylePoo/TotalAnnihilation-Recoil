#!/usr/bin/env python3
"""Reproduce TA's per-unit weapon damage lists with Recoil armor classes.

  armor.py REPO TA_OUT CMP

TA weapons list damage per target unit (damage = { default = 10, ARMFLASH = 200, ... }). Recoil only knows armor
classes, so units that every TA weapon treats the same are grouped into one class (36 groups with TA 3.1c data), each
weapon gets one damage entry per class, and gamedata/ArmorDefs.lua is rewritten.

One liberty: TA's anti-air lists predate some aircraft (Hunter, Typhoon, Seahawk, Albatross), so they are put in their
side's aircraft class and every class's value is the most common value among its members.
"""
import csv, json, os, re, sys
from collections import Counter, defaultdict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
REPO, TAOUT, CMP = sys.argv[1:4]
sys.argv = [sys.argv[0], REPO, TAOUT, CMP]
import apply as A  # noqa: E402

ta_w = {k: v['stats'] for k, v in json.load(open(os.path.join(TAOUT, 'weapons.json'))).items()}
ta_u = {k.lower(): {kk.lower(): vv for kk, vv in v['stats'].items()} for k, v in json.load(open(os.path.join(TAOUT, 'units.json'))).items()}
mapping = {r['repo_file']: r['ta_id'].lower() for r in csv.DictReader(open(os.path.join(CMP, 'unit_mapping.csv')))}
pairs = defaultdict(set)   # repo weapon -> TA weapons
for r in csv.DictReader(open(os.path.join(CMP, 'weapon_diff.csv'))):
    if r['repo_weapon'] and r['ta_weapon'] in ta_w:
        pairs[r['repo_weapon']].add(r['ta_weapon'])
# weapons identical to TA have no diff rows: pair by name
files = A.weapon_files()
for w in files:
    if w in ta_w and w not in pairs:
        pairs[w].add(w)


def lists(t):
    d = ta_w[t].get('damage') or {}
    return {k.lower(): A.fmt(v) for k, v in d.items() if k != 'default'}


def sig(tid):
    return tuple(sorted((t, l[tid]) for t in ta_w for l in [lists(t)] if tid in l))


# group units
groups = defaultdict(list)
for stem, tid in mapping.items():
    air = str(ta_u[tid].get('canfly', '0')) == '1'
    side = stem.split('_')[0].lower()
    key = ('aircraft', side) if air else sig(tid)
    groups[key].append(stem)


def name_group(key, members):
    if key and key[0] == 'aircraft':
        return '%s_aircraft' % key[1]
    if len(members) == 1:
        return members[0].lower() + '_armor'   # not the bare unit name: Recoil treats damage keys that name a unit specially
    if not key:
        return None   # default class
    ws = {t for t, _ in key}
    if ws == {'armemp_weapon'} and all(m.startswith('CORE') for m in members):
        return 'core_mobile' if dict(key)['armemp_weapon'] == '1800' else 'anti_nukes'
    if ws == {'armemp_weapon'}:
        return 'anti_nukes'
    if ws == {'cortron_weapon'}:
        return 'arm_mobile'
    return 'group_' + '_'.join(sorted(m.lower() for m in members))[:40]


classes = {}
for key, members in groups.items():
    n = name_group(key, members)
    if n:
        classes[n] = sorted(members)
print('armor classes:', len(classes), {k: len(v) for k, v in classes.items() if len(v) > 1})

# per class value for each TA weapon (majority over members)
cls_of = {m: c for c, ms in classes.items() for m in ms}
report = []
n_set = 0
for rw, tws in sorted(pairs.items()):
    if rw not in files:
        continue
    want = {}
    for c, ms in classes.items():
        vals = Counter()
        for t in tws:
            l = lists(t)
            for m in ms:
                if mapping[m] in l:
                    vals[l[mapping[m]]] += 1
        if vals:
            want[c] = vals.most_common(1)[0][0]
            if len(vals) > 1:
                report.append('%s vs %s: values %s, used %s' % (rw, c, dict(vals), want[c]))
    for f in files[rw]:
        path = os.path.join(REPO, 'Weapons', f)
        lines = open(path, encoding='latin-1').read().split('\n')
        s, e = A.find_block(lines, rw, '\t')
        ds = A.find_block(lines[s:e], 'damage', '\t\t')
        if not ds:
            continue
        a, b = s + ds[0], s + ds[1]
        # drop the old aircraft class and any class lines from an earlier run
        keep = [l for l in lines[a:b] if re.match(r'^\t\t\tdefault\s*=', l)]
        new = keep + ['\t\t\t%s = %s,' % (c, v) for c, v in sorted(want.items())]
        if new != lines[a:b]:
            n_set += 1
        lines[a:b] = new
        open(path, 'w', encoding='latin-1').write('\n'.join(lines))
print('weapon damage tables written:', n_set)
for r in report:
    print('  note:', r)

out = ['-- Armor classes: TA 3.1c per-unit weapon damage, grouped (generated by tools/ta-data/armor.py; do not edit by hand).',
       '-- TA weapons listed damage against individual units (e.g. the Immolator does 10 by default, 200 to a Flash);',
       '-- units that every TA weapon treats the same share a class. Units in no class take each weapon\'s default.',
       '-- Aircraft: one class per side (TA\'s lists predate some of them). Also read by the Defense Range widget.',
       '', 'local armorDefs = {']
for c in sorted(classes):
    out.append('\t%s = {' % c)
    out += ['\t\t"%s",' % m for m in classes[c]]
    out.append('\t},')
out += ['}', '', 'return armorDefs', '']
open(os.path.join(REPO, 'gamedata', 'ArmorDefs.lua'), 'w').write('\n'.join(out))
