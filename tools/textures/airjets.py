#!/usr/bin/env python3
"""Thruster flames for TA:Recoil aircraft (Airjets GL4 / LUPS AirJet entries), from the models' exhaust pieces.

  airjets.py [--report]

For every flying unit, finds S3O pieces named like an exhaust (thrust, jet, exhaust, engine, burner, nozzle; not
"flare", which are gun muzzles). Pieces named "vert..." and hovering aircraft (builders, transports, gunships) blow
down; fighters and bombers blow backward. Arm jets are blue-white, Core jets orange (matching the unit lights);
size from the model. Jets only show while the aircraft is active (flying).
Writes luaui/configs/lupsunitfxs_ta.lua, merged into effectUnitDefs by lupsunitfxs.lua.
"""
import argparse, glob, os, re, sys
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import unitlights as U

ROOT = U.ROOT
OUT = os.path.join(ROOT, 'luaui', 'configs', 'lupsunitfxs_ta.lua')
EXHAUST = re.compile(r'thrust|jet|exhaust|engine|burner|nozzle', re.I)
COLORS = {'arm': (0.55, 0.75, 1.0, 0.8), 'core': (1.0, 0.55, 0.15, 0.8)}


def flag(s, k):
    return bool(re.search(r'\b%s\s*=\s*(true|1)\b' % k, s, re.I))


def num(s, k):
    m = re.search(r'\b%s\s*=\s*([\d.]+)' % k, s, re.I)
    return float(m.group(1)) if m else 0.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--report', action='store_true')
    a = ap.parse_args()
    out = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'units', '*.lua'))):
        s = open(f).read()
        if not flag(s, 'canfly'):
            continue
        uname = os.path.splitext(os.path.basename(f))[0].lower()
        obj = re.search(r'objectname\s*=\s*"([^"]+)"', s, re.I).group(1).split('/')[-1]
        pieces, _, _ = U.read_s3o(os.path.join(ROOT, 'objects3d', obj))
        jets = [p['name'] for p in pieces if EXHAUST.search(p['name']) and 'flare' not in p['name'].lower()]
        if not jets:
            continue
        hover = flag(s, 'hoverattack') or num(s, 'workertime') > 0 or num(s, 'transportcapacity') > 0
        allv = np.concatenate([p['verts'][:, 0:3] for p in pieces if len(p['verts'])])
        size = float(np.linalg.norm(allv.max(0) - allv.min(0)))       # model diagonal, elmos
        width = round(float(np.clip(size * 0.06, 2.5, 6)), 1)
        length = round(float(np.clip(size * 0.45, 14, 45)))
        col = COLORS['arm' if uname.startswith('arm') else 'core']
        entries = []
        for j in jets:
            down = hover or j.lower().startswith('vert')
            entries.append((j, (0, -1, 0) if down else (0, 0, -1), width * (1.0 if down else 0.85), length))
        out[uname] = (col, entries)
        if a.report:
            print('%-34s %s %s' % (uname, 'hover' if hover else 'plane', ', '.join('%s%s' % (j, 'v' if v[1] else '') for j, v, _, _ in entries)))
    with open(OUT, 'w') as f:
        f.write('-- GENERATED by tools/textures/airjets.py: thruster flames on the exhaust pieces of TA:Recoil aircraft.\n'
                '-- Merged into effectUnitDefs by lupsunitfxs.lua; hand-made entries there win.\n'
                'return {\n')
        for uname in sorted(out):
            col, entries = out[uname]
            f.write('\t%s = {\n' % uname)
            for piece, v, w, l in entries:
                f.write("\t\t{class='AirJet', options={color={%s,%s,%s,%s}, width=%s, length=%d, piece=\"%s\", onActive=true, "
                        "emitVector={%d, %d, %d}}},\n" % (col[0], col[1], col[2], col[3], round(w, 1), l, piece, v[0], v[1], v[2]))
            f.write('\t},\n')
        f.write('}\n')
    print('%d aircraft with jets -> %s' % (len(out), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
