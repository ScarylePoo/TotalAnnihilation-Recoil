"""Flash (arm_flash) - Arm fast assault tank. Twin guns on side pods, turret at the rear.
Coordinates are ENGINE/global: X right, Y up, Z forward. mirror=True builds the -X twin sharing UVs."""
import math

UNIT = dict(
    res=1024,
    wreck=dict(seed=3, drop=['barrel2']),
    preview_pose={'turret': (0, -25, 0), 'sleeves': (-5, 0, 0)},
)


def build(k):
    # ------------------------------------------------------------------ base
    b = k.piece('base')
    s = 1  # build the +X side; mirror=True makes the -X side
    xi, xo = 7.5, 12.3
    belt = [(-11.6, 0.0), (11.6, 0.0), (14.6, 1.6), (14.9, 2.9), (13.4, 4.5), (-13.4, 4.5), (-14.9, 2.9), (-14.6, 1.6)]
    b.prism(xi, xo, belt, 'tread', bevel=0.15, mirror=True)
    for z in (-9.6, -4.8, 0.0, 4.8, 9.6):
        b.cyl((xi, 1.45, z), (xi - 0.4, 1.45, z), 1.2, 12, 'dark', mirror=True)
        b.cyl((xi - 0.4, 1.45, z), (xi - 0.65, 1.45, z), 0.5, 8, 'steel', mirror=True)
    for z in (-13.0, 13.0):
        b.cyl((xi, 2.5, z), (xi - 0.45, 2.5, z), 1.45, 12, 'dark', mirror=True)
        b.cyl((xi - 0.45, 2.5, z), (xi - 0.7, 2.5, z), 0.55, 8, 'steel', mirror=True)
    skirt = [(-13.4, 1.5), (13.4, 1.5), (15.1, 3.0), (14.4, 4.7), (-14.4, 4.7), (-15.1, 3.0)]
    b.hull([(12.2, y, z) for (z, y) in skirt] + [(12.75, y, z * 0.985) for (z, y) in skirt if y < 2] +
           [(12.95, y, z * 0.985) for (z, y) in skirt if y >= 2], 'paint', bevel=0.12, mirror=True)
    b.box((12.9, 3.05, -11.5), (13.25, 3.45, 11.5), 'team', bevel=0.06, mirror=True)
    for z0, z1 in ((-10.5, -6.0), (-4.0, 0.5), (2.5, 7.0)):
        b.box((12.9, 1.95, z0), (13.1, 2.75, z1), 'paint', bevel=0.05, mirror=True)
    top, bot = 5.6, 4.45
    b.hull([(7.0, top, -12.6), (13.3, top, -11.8), (13.3, top, 11.8), (7.0, top, 12.6),
            (8.0, 5.15, 15.6), (11.6, 5.15, 15.0), (8.0, 5.15, -15.6), (11.6, 5.15, -15.0),
            (7.0, bot, -12.6), (13.3, bot, -11.8), (13.3, bot, 11.8), (7.0, bot, 12.6),
            (7.9, 4.25, 16.4), (11.4, 4.25, 15.8), (7.9, 4.25, -16.4), (11.4, 4.25, -15.8)], 'paint', bevel=0.12, mirror=True)
    b.hull([(10.4, 5.6, -11.0), (12.9, 5.6, -10.6), (12.9, 5.6, 10.6), (10.4, 5.6, 11.0),
            (10.45, 5.78, -10.8), (12.8, 5.78, -10.5), (12.8, 5.78, 10.5), (10.45, 5.78, 10.8)], 'team', bevel=0.04, mirror=True)
    b.hull([(8.0, 5.24, 15.45), (11.6, 5.24, 14.85), (7.3, 5.68, 13.2), (13.0, 5.68, 12.5),
            (8.0, 5.36, 15.4), (11.6, 5.36, 14.8), (7.3, 5.78, 13.2), (13.0, 5.78, 12.5)], 'hazard', bevel=0.03, mirror=True)
    b.box((8.2, 5.6, -12.2), (10.8, 6.5, -8.6), 'dark', bevel=0.08, mirror=True)
    b.box((8.0, 6.2, -12.0), (11.0, 6.35, -8.8), 'dark', bevel=0.03, mirror=True)
    # centre hull (crosses x=0: not mirrored)
    b.prism(-7.3, 7.3, [(-14.2, 3.1), (13.4, 3.1), (15.8, 4.4), (13.0, 6.3), (-14.4, 6.3), (-15.0, 4.6)], 'paint2', bevel=0.15)
    b.hull([(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(5.6, 6.25, -15.0), (5.6, 6.25, 9.6), (4.9, 7.5, -14.2), (4.9, 7.5, 8.0)]], 'paint', bevel=0.12)
    b.hull([(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(1.8, 6.25, 9.8), (1.8, 6.25, 12.6), (1.4, 7.0, 10.0), (1.4, 7.0, 11.6)]], 'paint', bevel=0.08)
    b.hull([(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(1.1, 6.55, 12.2), (1.1, 6.8, 11.62), (1.1, 6.62, 12.32), (1.1, 6.87, 11.74)]], 'lightc', bevel=0.0)
    b.box((4.4, 4.75, 14.0), (6.3, 5.65, 15.25), 'dark', bevel=0.08, mirror=True)
    b.box((4.6, 4.9, 15.2), (6.1, 5.5, 15.33), 'lightw', bevel=0.0, mirror=True)
    b.box((2.0, 3.4, 15.2), (3.0, 4.0, 16.0), 'dark', bevel=0.06, mirror=True)
    b.hull([(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(3.6, 5.0, 14.75), (3.6, 5.95, 13.3), (3.6, 5.12, 14.85), (3.6, 6.07, 13.4)]], 'hazard', bevel=0.03)
    for z in (3.0, 4.0, 5.0, 6.0):
        b.box((-3.8, 7.45, z), (-0.6, 7.62, z + 0.55), 'dark', bevel=0.0)
    b.cyl((2.6, 7.45, 4.6), (2.6, 7.68, 4.6), 1.1, 14, 'paint', bevel=0.05)
    b.cyl((2.6, 7.68, 4.6), (2.6, 7.8, 4.6), 0.35, 8, 'dark')
    b.box((-4.4, 6.45, -15.25), (4.4, 7.35, -14.9), 'black', bevel=0.0)
    for y in (6.55, 6.8, 7.05):
        b.box((-4.2, y, -15.4), (4.2, y + 0.14, -15.0), 'dark', bevel=0.03)
    for z in (-14.0, -13.3):
        b.box((-3.2, 7.45, z), (3.2, 7.62, z + 0.45), 'dark', bevel=0.0)
    b.cyl((6.3, 5.6, -14.6), (6.3, 7.4, -14.6), 0.5, 10, 'dark', bevel=0.04, mirror=True)
    b.cyl((6.3, 7.4, -14.6), (6.3, 7.5, -14.6), 0.34, 10, 'black', mirror=True)
    b.cyl((-12.3, 5.6, -14.0), (-12.3, 6.3, -14.0), 0.32, 8, 'dark')
    b.cyl((-12.3, 6.3, -14.0), (-12.3, 11.4, -14.0), 0.08, 6, 'steel', r2=0.04)
    b.cyl((-12.3, 11.4, -14.0), (-12.3, 11.6, -14.0), 0.13, 6, 'lightc')

    # ---------------------------------------------------------------- turret
    t = k.piece('turret'); A = t.at
    t.cyl(A(0, 0, 0), A(0, 0.45, 0), 3.5, 16, 'dark', bevel=0.06)
    t.hull([A(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(3.2, 0.45, -3.5), (3.4, 0.45, -1.0), (3.4, 0.45, 2.2), (2.0, 0.45, 4.3),
             (2.5, 3.4, -3.0), (2.7, 3.4, -0.8), (2.7, 3.4, 1.4), (1.6, 3.4, 2.8)]], 'paint', bevel=0.12)
    t.hull([A(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(1.9, 3.38, -2.4), (2.05, 3.38, -0.6), (2.05, 3.38, 1.1), (1.2, 3.38, 2.25),
             (1.85, 3.5, -2.35), (2.0, 3.5, -0.6), (2.0, 3.5, 1.05), (1.15, 3.5, 2.2)]], 'team', bevel=0.03)
    t.cyl(A(-0.9, 3.45, 0.4), A(-0.9, 3.75, 0.4), 0.85, 12, 'paint', bevel=0.05)
    t.box(A(-1.3, 3.75, 0.3), A(-0.5, 3.85, 0.5), 'dark', bevel=0.0)
    t.hull([A(x, y, z) for x, y, z in
            [(0.4, 3.45, -2.5), (1.9, 3.45, -2.5), (0.4, 3.45, -0.8), (1.9, 3.45, -0.8),
             (0.55, 4.35, -2.3), (1.75, 4.35, -2.3), (0.55, 4.35, -1.05), (1.75, 4.35, -1.05)]], 'dark', bevel=0.07)
    t.box(A(0.75, 3.75, -0.85), A(1.55, 4.1, -0.72), 'lightc', bevel=0.0)
    t.box(A(2.85, 0.95, -0.7), A(3.55, 2.45, 1.7), 'dark', bevel=0.1, mirror=True)
    t.hull([A(x * sx, y, z) for sx in (-1, 1) for x, y, z in
            [(2.2, 0.9, -3.2), (2.2, 2.9, -3.0), (2.0, 1.0, -4.3), (1.9, 2.7, -4.2)]], 'paint', bevel=0.08)
    t.box(A(0.85, 1.3, -4.45), A(1.55, 2.4, -4.2), 'dark', bevel=0.03, mirror=True)
    t.box(A(-0.35, 1.3, -4.45), A(0.35, 2.4, -4.2), 'dark', bevel=0.03)

    # --------------------------------------------------------------- sleeves
    sv = k.piece('sleeves'); S = sv.at
    x = 4.56
    sv.cyl(S(x, 1.70, -1.6), S(x, 1.70, 4.6), 1.25, 8, 'paint2', rot=math.pi / 8, bevel=0.06, mirror=True)
    sv.cyl(S(x, 1.70, 4.6), S(x, 1.70, 5.45), 1.25, 8, 'paint2', r2=0.85, rot=math.pi / 8, mirror=True)
    sv.cyl(S(x, 1.70, -1.95), S(x, 1.70, -1.6), 0.85, 8, 'dark', r2=1.12, rot=math.pi / 8, mirror=True)
    for z0, z1 in ((0.3, 0.75), (3.1, 3.45)):
        sv.cyl(S(x, 1.70, z0), S(x, 1.70, z1), 1.3, 8, 'dark', rot=math.pi / 8, bevel=0.03, mirror=True)
    sv.box(S(x - 0.9, 2.6, -1.2), S(x + 0.9, 3.05, 3.9), 'team', bevel=0.05, mirror=True)
    sv.box(S(3.35, 2.25, -0.9), S(4.1, 2.95, 2.0), 'dark', bevel=0.07, mirror=True)
    sv.cyl(S(-3.9, 1.70, 0.5), S(3.9, 1.70, 0.5), 0.5, 10, 'steel')

    # --------------------------------------------------------------- barrels
    br = k.piece('barrel1'); B = br.at
    br.cyl(B(0, 0, -3.4), B(0, 0, 6.4), 0.46, 10, 'steel')
    br.cyl(B(0, 0, 0.0), B(0, 0, 0.8), 0.62, 10, 'dark', bevel=0.05)
    br.cyl(B(0, 0, 3.0), B(0, 0, 3.3), 0.55, 10, 'dark')
    br.cyl(B(0, 0, 6.3), B(0, 0, 7.62), 0.66, 8, 'dark', rot=math.pi / 8, bevel=0.05)
    br.cyl(B(0, 0, 7.6), B(0, 0, 7.68), 0.3, 8, 'black')
    for sx in (-1, 1):
        br.box(B(0.55 * sx, -0.2, 6.6), B(0.72 * sx, 0.2, 6.95), 'black', bevel=0.0)
        br.box(B(0.55 * sx, -0.2, 7.1), B(0.72 * sx, 0.2, 7.45), 'black', bevel=0.0)
    k.clone('barrel2', 'barrel1')
