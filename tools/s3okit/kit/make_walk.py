"""Generate scripts/headers/walk.lua (shared biped + quad walk for TA:Recoil walkers) from Splinter Faction's
common.WalkScript.  usage: python3 make_walk.py [SplinterFaction checkout] [output]

Biped: SF's Skeletor-generated keyframes unchanged, except SF's `turret` line is dropped and the pelvis bob is
scaled by unit size. Quad: the same keys on diagonal leg pairs (lf+rb take the left leg's keys, rf+lb the right
leg's; y/z turns negated on the leg that changes side), hip twist reduced to 30 %. Hexa: a procedural alternating tripod
gait with per-leg calibrated rotation signs (see the HEXA block)."""
import re, sys, os

SF = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/SplinterFaction'
KIT = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(KIT, '..', '..', '..', 'scripts', 'headers', 'walk.lua')

src = open(os.path.join(SF, 'Scripts/headers/common_includes_lus.lua'), encoding='latin-1').read().replace('\r', '').split('\n')


def function_body(start_pat, after=0):
    i = next(n for n in range(after, len(src)) if start_pat in src[n])
    ind = len(src[i]) - len(src[i].lstrip('\t'))
    j = next(n for n in range(i + 1, len(src)) if src[n].strip() == 'end' and len(src[n]) - len(src[n].lstrip('\t')) == ind)
    return src[i + 1:j], j


ws = next(n for n, l in enumerate(src) if 'WalkScript = function' in l)
walk_body, end_walk = function_body('local function Walk()', ws)
stop_body, _ = function_body('local function StopWalking()', end_walk)
# Signal/SetSignalMask are done by our wrapper; SF's turret line belongs to SF's units
skip = re.compile(r'^\s*(Signal|SetSignalMask)\(SIG_WALK\)|turret')
walk_body = [l for l in walk_body if not skip.search(l)]
stop_body = [l for l in stop_body if not skip.search(l)]

TURN = re.compile(r'^(\s*)Turn\((\w+), ([xyz])_axis, (-?[\d.]+), ([\d.]+) \* speedMult\)(.*)$')
MOVE = re.compile(r'^(\s*)Move\(pelvis, y_axis, (-?[\d.]+), ([\d.]+) \* speedMult\)(.*)$')
LEG = re.compile(r'^([lr])(thigh|leg|foot)$')
QMAP = {'l': [('lf', 1), ('rb', -1)], 'r': [('rf', 1), ('lb', -1)]}


def bob_line(l):
    m = MOVE.match(l)
    if m:
        i, v, s, c = m.groups()
        return f'{i}Move(pelvis, y_axis, {v} * bob, {s} * bob * speedMult){c}'
    return l


def quad_line(l, stop=False):
    m = TURN.match(l)
    if m:
        i, p, ax, v, s, c = m.groups()
        mm = LEG.match(p)
        if mm:
            return [f'{i}Turn({q}{mm.group(2)}, {ax}_axis, {float(v) * (sg if ax in "yz" else 1):.6f}, {s} * speedMult)'
                    for q, sg in QMAP[mm.group(1)]]
        if p == 'pelvis' and ax == 'y':
            return [f'{i}Turn(pelvis, y_axis, {float(v) * 0.3:.6f}, {float(s) * 0.3:.6f} * speedMult)']
    return [bob_line(l)]


def reindent(lines, base=2):
    out = []
    mins = min(len(l) - len(l.lstrip('\t')) for l in lines if l.strip())
    for l in lines:
        s = l.lstrip('\t')
        out.append('\t' * (base + len(l) - len(s) - mins) + s if s else '')
    t = '\n'.join(out)
    # footfall hook: once per step, at the pelvis' lowest key
    return re.sub(r'(\n(\t*)Move\(pelvis, y_axis, -1\.180000 \* bob[^\n]*)', r'\1\n\2if onStep then onStep() end', t)


HDR = '''-- Shared walk animations for TA:Recoil walkers (Lua unit scripts). GENERATED by tools/s3okit/kit/make_walk.py from
-- Splinter Faction's common.WalkScript: edit the generator, not this file.
--
-- Every legged unit is remodelled on one standard skeleton (tools/s3okit/s3o-remodel-handoff.md, "Walkers"):
--   biped: pelvis > legs > {r,l}thigh > {r,l}leg > {r,l}foot            (r = -X side)
--   quad:  pelvis > legs > {rf,lf,rb,lb}thigh > ..leg > ..foot           (f front, b back)
-- with SF Federation proportions scaled by pelvis height, so one set of keyframes fits every walker.
-- Biped keys: SF's (Beherith's Skeletor_S3O, 2_legged_walk_animation_vb1.blend), turret line dropped, pelvis bob
-- scaled by size. Quad: the same keys on diagonal pairs (lf+rb = left keys, rf+lb = right keys, y/z negated on the
-- leg that changes side), hip twist at 30 %. Cadence = speed / leg length, so feet do not skate at any size.
--
-- Usage in a unit script (piece variables must be GLOBALS, as in SF):
--   pelvis, legs, rthigh, rleg, rfoot, lthigh, lleg, lfoot = piece('pelvis', 'legs', 'rthigh', 'rleg', ...)
--   local walk = include("headers/walk.lua")
--   walk.Biped()          -- or walk.Quad() / walk.Hexa(); defines script.StartMoving and script.StopMoving
--   walk.Biped({onStep = function() ... end})   -- optional, called once per footfall

local REF_HEIGHT = 23.0        -- pelvis height of SF's fedbear, on which the keys were made
local ANIM_FRAMES = 4
local SIG_WALK = 2^30          -- high bit: unit scripts use the low bits for their aim signals

local function sizeScale()
	local _, py = Spring.GetUnitPiecePosition(unitID, pelvis)
	return ((py and py > 2) and py or REF_HEIGHT) / REF_HEIGHT
end

local function speedParams(scale)
	local speed = UnitDefs[Spring.GetUnitDefID(unitID)].speed * 0.01 / scale
	if speed <= 0 then
		return 0, 300
	end
	local sleepFrames = math.floor(ANIM_FRAMES / speed + 0.5)
	if sleepFrames < 1 then
		sleepFrames = 1
	end
	return 1 / sleepFrames, 33 * sleepFrames
end

local function install(walkFn, stopFn)
	local walking = false
	local function Walk()
		Signal(SIG_WALK)
		SetSignalMask(SIG_WALK)
		walkFn()
	end
	local function StopWalking()
		Signal(SIG_WALK)
		SetSignalMask(SIG_WALK)
		stopFn()
	end
	function script.StartMoving()
		if not walking then
			walking = true
			StartThread(Walk)
		end
	end
	function script.StopMoving()
		walking = false
		StartThread(StopWalking)
	end
end

local walk = {}
'''


def fn(name, body, stop):
    return f'''
function walk.{name}(opts)
	local onStep = opts and opts.onStep
	install(function()
		local bob = sizeScale()
		local function GetSpeedParams() return speedParams(bob) end
{reindent(body)}
	end, function()
		local bob = sizeScale()
		local speedMult = 0.5 * speedParams(bob) -- slower restore speed for the last step
{reindent([l for l in stop if 'local speedMult' not in l])}
	end)
end
'''


bip_w = [bob_line(l) for l in walk_body]
bip_s = [bob_line(l) for l in stop_body]
quad_w = [x for l in walk_body for x in quad_line(l)]
quad_s = [x for l in stop_body for x in quad_line(l, stop=True)]
HEXA = r"""
-- Hexapod (Spider, Scarab, Roach; user decision 2026-10-31): alternating tripod gait, lf+rm+lb then rf+lm+rb.
-- Sideways spider legs (skeleton.py HEXA): a leg swings on its thigh's yaw (y) and lifts on its thigh's roll (z); the
-- knee tucks while the leg is up. All six legs have identical local offsets (one UV set); the front/rear splay is the
-- base yaw SPLAY applied here. Rotation directions are CALIBRATED at creation: each thigh is nudged and its foot's
-- movement measured with Spring.GetUnitPiecePosition (the engine recomputes a dirty piece's transform on read, so an
-- instant Turn is visible at once; if a read ever comes back stale the measurement is repeated a frame later). So no
-- axis-handedness assumption can make a leg move the wrong way. Cadence follows the unit's actual speed and the
-- measured leg reach, so planted feet do not skate. The result is published as the private unit rules param
-- hexaWalkCalib (1 = measured at once, 2 = measured a frame later, -1 = failed: default signs).
-- Usage: local hexaReady = walk.Hexa();  function script.Create() hexaReady() ... end
-- opts: splay, swing, lift (radians), knee (tuck as a fraction of lift), minStep (seconds per step), onStep.
function walk.Hexa(opts)
	opts = opts or {}
	local onStep = opts.onStep
	local SPLAY = opts.splay or math.rad(30)      -- front legs yaw forward, rear legs backward
	local SWING = opts.swing or math.rad(16)      -- stride: yaw swing either side of the base yaw
	local LIFT = opts.lift or math.rad(20)        -- thigh roll that lifts a swinging leg
	local KNEE = opts.knee or 0.6                 -- knee tuck while lifted, fraction of LIFT
	local MIN_STEP = opts.minStep or 0.25         -- fastest step (s): tiny units would otherwise flicker
	local GetPos = Spring.GetUnitPiecePosition
	local legs = {
		{thigh = rfthigh, leg = rfleg, foot = rffoot, base = 1},  {thigh = lfthigh, leg = lfleg, foot = lffoot, base = 1},
		{thigh = rmthigh, leg = rmleg, foot = rmfoot, base = 0},  {thigh = lmthigh, leg = lmleg, foot = lmfoot, base = 0},
		{thigh = rbthigh, leg = rbleg, foot = rbfoot, base = -1}, {thigh = lbthigh, leg = lbleg, foot = lbfoot, base = -1},
	}
	local tripodA = {[2] = true, [3] = true, [6] = true}   -- lf, rm, lb
	local calibrated = false
	local maxSpeed = UnitDefs[unitDefID].speed      -- elmos per second
	local stroke = 1                                -- body travel per step (elmos), from the measured reach

	local function probe(axis, deferred)
		local before, d = {}, {}
		for i, L in ipairs(legs) do
			before[i] = {GetPos(unitID, L.foot)}
			Turn(L.thigh, axis, 0.3)
		end
		if deferred then Sleep(1) end
		for i, L in ipairs(legs) do
			local p = {GetPos(unitID, L.foot)}
			d[i] = {p[1] - before[i][1], p[2] - before[i][2], p[3] - before[i][3]}
			Turn(L.thigh, axis, 0)
		end
		if deferred then Sleep(1) end
		return d
	end
	local function solve(deferred)
		local dz, dy = probe(z_axis, deferred), probe(y_axis, deferred)
		for i = 1, #legs do
			if math.abs(dz[i][2]) < 1e-3 or math.abs(dy[i][3]) < 1e-3 then return false end
		end
		for i, L in ipairs(legs) do
			L.liftSign = (dz[i][2] > 0) and 1 or -1     -- +z roll raises this foot?
			L.fwdSign = (dy[i][3] > 0) and 1 or -1      -- +y yaw moves this foot forward?
		end
		return true
	end
	local function finish(mode)
		local reach = 0
		for _, L in ipairs(legs) do
			L.liftSign, L.fwdSign = L.liftSign or 1, L.fwdSign or 1
			local hx, _, hz = GetPos(unitID, L.thigh)
			local fx, _, fz = GetPos(unitID, L.foot)
			reach = reach + math.sqrt((fx - hx) ^ 2 + (fz - hz) ^ 2) / #legs
			Turn(L.thigh, y_axis, L.base * SPLAY * L.fwdSign)
		end
		-- foot travel along z per step, averaged over the middle (unsplayed) and the splayed legs
		stroke = math.max(1, 2 * reach * math.sin(SWING) * (1 + 2 * math.cos(SPLAY)) / 3)
		Spring.SetUnitRulesParam(unitID, "hexaWalkCalib", mode, {private = true})
		if mode < 0 then
			Spring.Echo("walk.Hexa: leg calibration failed for " .. UnitDefs[unitDefID].name .. ", using default signs")
		end
		calibrated = true
	end
	local function calibrate()
		if solve(false) then
			finish(1)
		else
			StartThread(function() finish(solve(true) and 2 or -1) end)
		end
	end
	local function waitReady()
		while not calibrated do Sleep(33) end
	end

	install(function()
		waitReady()
		local phase = 0
		while true do
			local vx, _, vz = Spring.GetUnitVelocity(unitID)
			local v = math.max(math.sqrt(vx * vx + vz * vz) * 30, 0.4 * maxSpeed, 1)   -- turning on the spot still steps
			local T = math.max(MIN_STEP, stroke / v)                                     -- seconds per step
			local swingRate = 2 * SWING / T
			for i, L in ipairs(legs) do
				local swinging = (tripodA[i] ~= nil) == (phase == 0)
				-- the swinging tripod lifts and reaches forward, the planted tripod pushes back over the whole step
				Turn(L.thigh, y_axis, (L.base * SPLAY + (swinging and SWING or -SWING)) * L.fwdSign,
					swinging and swingRate * 1.25 or swingRate)
				if swinging then
					Turn(L.thigh, z_axis, LIFT * L.liftSign, LIFT / (0.3 * T))
					Turn(L.leg, z_axis, -KNEE * LIFT * L.liftSign, KNEE * LIFT / (0.3 * T))
				end
			end
			Sleep(math.max(33, 500 * T))
			for i, L in ipairs(legs) do
				if (tripodA[i] ~= nil) == (phase == 0) then
					Turn(L.thigh, z_axis, 0, LIFT / (0.35 * T))
					Turn(L.leg, z_axis, 0, KNEE * LIFT / (0.35 * T))
				end
			end
			Sleep(math.max(33, 500 * T))
			if onStep then onStep() end
			phase = 1 - phase
		end
	end, function()
		waitReady()
		for _, L in ipairs(legs) do
			Turn(L.thigh, y_axis, L.base * SPLAY * L.fwdSign, SWING * 3)
			Turn(L.thigh, z_axis, 0, LIFT * 3)
			Turn(L.leg, z_axis, 0, LIFT * 3)
		end
	end)
	return function() if not calibrated then calibrate() end end   -- call from script.Create (signs + rest splay)
end
"""

lua = HDR + fn('Biped', bip_w, bip_s) + fn('Quad', quad_w, quad_s) + HEXA + '\nreturn walk\n'
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write(lua)
print(os.path.relpath(OUT), len(lua.splitlines()), 'lines,', lua.count('Turn('), 'turns')
