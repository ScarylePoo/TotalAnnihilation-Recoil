#!/usr/bin/env python3
"""COB -> Lua unit script (LUS) transpiler.

    python3 cob2lus.py <stem> [...]      convert named units (write scripts/<stem>.lua and the def's script line)
    python3 cob2lus.py --all             every unit still on COB, plus every script this tool generated earlier
    python3 cob2lus.py --check <stem>    print the result, write nothing
    options: --force  overwrite a generated script even if it was edited by hand since (see HEADER_RE)

COB is a stack machine compiled from BOS, so its control flow is regular and the structure can be rebuilt:
    if    = cond, jne else, body, [jump end, else:, body2], end:
    while = start: cond, jne end, body, jump start
Anything that does not fit these shapes, or that this tool cannot express, raises Unsupported: nothing is emitted for
that unit, it is listed at the end, and it must be ported by hand (HAND below).

What differs between COB and LUS, and how it is handled here (all verified in Recoil's CobInstance, CobThread,
LuaUnitScript and the stock unit_script gadget):
- Units: COB angles 65536 = 360 deg, linear 65536 = 1 elmo. heading and pitch are radians in Lua, so variables holding
  them are typed 'rad' and everything mixed with them is converted (see Emit.rad).
- Sign: the engine negates COB turn/turn-now/spin values on z and move/move-now values on x. Emitted here.
- A COB turn or move at speed 0 does nothing. Lua treats it as "now". Dropped (a runtime speed is listed as a warning).
- Truthiness: COB 0 is false, Lua 0 is true. Conditions and the aim return are made boolean.
- By-reference args: Query*/AimFrom*/SweetSpot piece, Killed corpse type -> return values. Piece numbers differ, so
  constants flowing there become piece names (a variable carrying them is typed 'piece').
- Callin args: RockUnit/HitByWeapon get 500 * dir in COB, in (z, x) order; Lua gets (x, z) unscaled. SetSpeed and
  SetDirection are WindChanged and ExtractionRateChanged in Lua. SetMaxReloadTime does not exist in Lua.
- Threads: Lua callins the gadget does not wrap run outside a coroutine, where Sleep/WaitFor/SetSignalMask raise. Such
  a callin gets a StartThread when its body can block.
- Lua's Signal cannot kill the running thread, COB's can: warned about (see lint_self_signal).
- start-script args reach the new thread in reverse order (CobThread::InitStack), call-script args in order.
- TargetCleared is not a callin of this engine: it never ran. Nothing is generated for it.
- A signal shared across weapons makes each cancel the other; shared restore threads then snap back the other weapon.
  Each weapon gets its own aim signal and restore threads get their own (split_weapon_signals).
"""
