# ---------------------------------------------------------------------------------------- decoding

def decode(path):
    """-> (pieces, {name: start pc}, {pc: (op, operands, next pc)}, nstatic, names in file order)"""
    d = open(path, 'rb').read()
    (ver, nscr, npc, codelen, nstatic, _u, o_codeidx, o_names, o_pieces, o_code) = struct.unpack('<10i', d[:40])
    if ver not in (4, 6):
        raise Unsupported(f'not a COB file (version {ver})')
    code = struct.unpack(f'<{codelen}i', d[o_code:o_code + codelen * 4])

    def cstr(o):
        return d[o:d.index(b'\0', o)].decode('latin-1')
    names = [cstr(struct.unpack_from('<i', d, o_names + 4 * i)[0]) for i in range(nscr)]
    starts = [struct.unpack_from('<i', d, o_codeidx + 4 * i)[0] for i in range(nscr)]
    pieces = [cstr(struct.unpack_from('<i', d, o_pieces + 4 * i)[0]).lower() for i in range(npc)]
    ins = {}
    for s in sorted(set(starts)):
        pc = s
        while pc < codelen:
            if code[pc] not in OPS:
                break                   # dead data after a final return: never executed
            nm, n = OPS[code[pc]]
            ins[pc] = (nm, code[pc + 1:pc + 1 + n], pc + 1 + n)
            pc += 1 + n
    return pieces, names, starts, ins, nstatic, codelen


# ---------------------------------------------------------------------------------------- IR

class C:
    __slots__ = ('v',)
    def __init__(self, v): self.v = v


class V:
    """variable: kind 'l' local slot (of the current function) or 's' static"""
    __slots__ = ('k', 'i')
    def __init__(self, k, i): self.k, self.i = k, i


class B:
    __slots__ = ('op', 'a', 'b')
    def __init__(self, op, a, b): self.op, self.a, self.b = op, a, b


class U:
    __slots__ = ('op', 'a')
    def __init__(self, op, a): self.op, self.a = op, a


class Rand:
    __slots__ = ('a', 'b')
    def __init__(self, a, b): self.a, self.b = a, b


class Get:
    __slots__ = ('var', 'args')
    def __init__(self, var, args): self.var, self.args = var, args


class S:
    """statement: kind + fields"""
    __slots__ = ('kind', 'f')
    def __init__(self, kind, **f): self.kind, self.f = kind, f
    def __getattr__(self, n):
        try:
            return self.f[n]
        except KeyError:
            raise AttributeError(n)


BINOPS = {'add': '+', 'sub': '-', 'mul': '*', 'div': '/', 'mod': '%', 'and': 'band', 'or': 'bor', 'xor': 'bxor', 'lt': '<', 'le': '<=', 'gt': '>',
          'ge': '>=', 'eq': '==', 'ne': '~=', 'land': 'and', 'lor': 'or', 'lxor': 'xor'}


def cdiv(a, b):
    if b == 0:
        return 1000
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q


def fold(op, a, b):
    return {'add': lambda: a + b, 'sub': lambda: a - b, 'mul': lambda: a * b, 'div': lambda: cdiv(a, b),
            'mod': lambda: 0 if b == 0 else abs(a) % abs(b) * (1 if a >= 0 else -1),
            'and': lambda: a & b, 'or': lambda: a | b, 'xor': lambda: a ^ b,
            'lt': lambda: int(a < b), 'le': lambda: int(a <= b), 'gt': lambda: int(a > b), 'ge': lambda: int(a >= b),
            'eq': lambda: int(a == b), 'ne': lambda: int(a != b), 'land': lambda: int(bool(a) and bool(b)),
            'lor': lambda: int(bool(a) or bool(b)), 'lxor': lambda: int(bool(a) != bool(b))}[op]()


class Decompiler:
    def __init__(self, ins, names, starts, fname):
        self.ins, self.names, self.starts, self.fname = ins, names, starts, fname
        self.nclv = 0
        self.maxlocal = -1

    def fail(self, msg):
        raise Unsupported(f'{self.fname}: {msg}')

    def prev_pc(self, target, lo):
        """pc of the instruction that ends right at target, scanning from lo"""
        pc = lo
        last = None
        while pc < target:
            if pc not in self.ins:
                self.fail(f'jump into undecoded code at {pc}')
            last = pc
            pc = self.ins[pc][2]
        if pc != target:
            self.fail(f'jump target {target} is inside an instruction')
        return last

    def region(self, start, end):
        out, st = [], []
        pc = start
        stmt_start = start

        def pop():
            if not st:
                self.fail(f'stack underflow at {pc}')
            return st.pop()

        while pc < end:
            if pc not in self.ins:
                self.fail(f'undecoded instruction at {pc}')
            nm, ops, nxt = self.ins[pc]
            if nm == 'pushc':
                st.append(C(ops[0]))
            elif nm in ('pushl', 'pushs'):
                if nm == 'pushl':
                    self.maxlocal = max(self.maxlocal, ops[0])
                st.append(V('l' if nm == 'pushl' else 's', ops[0]))
            elif nm == 'clv':
                if self.ins.get(nxt, ('',))[0] == 'return':
                    st.append(C(0))     # `clv; return` is how some compilers wrote return(0)
                elif st:
                    self.fail('clv with a non-empty stack')
                else:
                    self.nclv += 1
            elif nm in BINOPS:
                b = pop(); a = pop()
                st.append(C(fold(nm, a.v, b.v)) if isinstance(a, C) and isinstance(b, C) else B(nm, a, b))
            elif nm in ('not', 'lnot'):
                a = pop()
                st.append(C(int(a.v == 0) if nm == 'lnot' else ~a.v) if isinstance(a, C) else U(nm, a))
            elif nm == 'rand':
                b = pop(); a = pop()
                st.append(Rand(a, b))
            elif nm == 'get-unit-value':
                st.append(Get(pop(), []))
            elif nm == 'get':
                a4 = pop(); a3 = pop(); a2 = pop(); a1 = pop(); var = pop()
                st.append(Get(var, [a1, a2, a3, a4]))
            elif nm in ('popl', 'pops'):
                if nm == 'popl':
                    self.maxlocal = max(self.maxlocal, ops[0])
                out.append(S('assign', var=V('l' if nm == 'popl' else 's', ops[0]), e=pop()))
            elif nm == 'pop-stack':
                pop()
            elif nm in ('turn', 'move'):
                dest = pop(); speed = pop()
                out.append(S(nm, p=ops[0], ax=ops[1], dest=dest, speed=speed))
            elif nm in ('turn-now', 'move-now'):
                out.append(S(nm[:4], p=ops[0], ax=ops[1], dest=pop(), speed=None))
            elif nm == 'spin':
                speed = pop(); accel = pop()
                out.append(S('spin', p=ops[0], ax=ops[1], speed=speed, accel=accel))
            elif nm == 'stop-spin':
                out.append(S('stopspin', p=ops[0], ax=ops[1], decel=pop()))
            elif nm == 'sleep':
                out.append(S('sleep', e=pop()))
            elif nm == 'wait-turn':
                out.append(S('waitturn', p=ops[0], ax=ops[1]))
            elif nm == 'wait-move':
                out.append(S('waitmove', p=ops[0], ax=ops[1]))
            elif nm in ('show', 'hide'):
                out.append(S(nm, p=ops[0]))
            elif nm in ('cache', 'dont-cache', 'shade', 'dont-shade'):
                pass
            elif nm == 'emit-sfx':
                out.append(S('emit', p=ops[0], e=pop()))
            elif nm == 'explode':
                out.append(S('explode', p=ops[0], e=pop()))
            elif nm == 'signal':
                out.append(S('signal', e=pop()))
            elif nm == 'set-signal-mask':
                out.append(S('setmask', e=pop()))
            elif nm == 'set':
                val = pop(); var = pop()
                out.append(S('setval', var=var, e=val))
            elif nm == 'attach':
                _x = pop(); p = pop(); u = pop()
                out.append(S('attach', unit=u, piece=p))
            elif nm == 'drop':
                out.append(S('drop', unit=pop()))
            elif nm in ('call', 'start'):
                n = ops[1]
                args = st[len(st) - n:] if n else []
                if n:
                    del st[len(st) - n:]
                if st:
                    self.fail(f'{nm} with extra values on the stack')
                if nm == 'start':
                    args = args[::-1]   # CobThread::InitStack pops the args onto the new stack: slot 0 is the last pushed
                out.append(S(nm, fn=self.names[ops[0]], args=args))
            elif nm == 'return':
                out.append(S('return', e=pop()))
                if st:
                    self.fail('return with extra values on the stack')
                return out              # the rest of a region after a return is dead code
            elif nm == 'jump':
                self.fail(f'unstructured jump at {pc} to {ops[0]}')
            elif nm == 'jne':
                cond = pop()
                if st:
                    self.fail('branch with extra values on the stack')
                target = ops[0]
                if target > end or target < nxt:
                    self.fail(f'branch at {pc} to {target} leaves its block [{start}, {end})')
                last = self.prev_pc(target, nxt) if target > nxt else None
                lastop = self.ins[last] if last is not None else None
                if lastop and lastop[0] == 'jump' and lastop[1][0] == stmt_start:
                    body = self.region(nxt, last)
                    if isinstance(cond, C) and cond.v == 0:
                        pass
                    else:
                        out.append(S('while', cond=cond, body=body))
                    pc = target
                elif lastop and lastop[0] == 'jump' and lastop[1][0] > target:
                    dest = lastop[1][0]
                    if dest > end:
                        self.fail(f'else block at {pc} runs past its parent')
                    self.prev_pc(dest, target)
                    then, other = self.region(nxt, last), self.region(target, dest)
                    self.append_if(out, cond, then, other)
                    pc = dest
                elif lastop and lastop[0] == 'jump' and lastop[1][0] == target:
                    self.append_if(out, cond, self.region(nxt, last), [])
                    pc = target
                elif lastop and lastop[0] == 'jump':
                    self.fail(f'jump at {last} to {lastop[1][0]} is neither loop nor else')
                else:
                    self.append_if(out, cond, self.region(nxt, target), [])
                    pc = target
                stmt_start = pc
                continue
            else:
                self.fail(f'cannot express opcode {nm}')
            pc = nxt
            if not st:
                stmt_start = pc
        if st:
            self.fail('values left on the stack at the end of a block')
        return out

    def append_if(self, out, cond, then, other):
        if isinstance(cond, C):
            out.extend(then if cond.v != 0 else other)
        else:
            out.append(S('if', cond=cond, then=then, other=other))


def script_end(start, starts, codelen):
    later = [s for s in starts if s > start]
    return min(later) if later else codelen


class Fn:
    def __init__(self, name, body, nslots):
        self.name, self.body, self.nslots = name, body, nslots
        self.nargs = 0
        self.called = False


def walk(body):
    for s in body:
        yield s
        if s.kind == 'if':
            yield from walk(s.then)
            yield from walk(s.other)
        elif s.kind == 'while':
            yield from walk(s.body)


def exprs_of(s):
    for k, v in s.f.items():
        if k in ('then', 'other', 'body', 'var') and not (k == 'var' and s.kind == 'setval'):
            continue
        if isinstance(v, (C, V, B, U, Rand, Get)):
            yield k, v
        elif isinstance(v, list) and k == 'args':
            for a in v:
                yield k, a


def leaves(e):
    if isinstance(e, B):
        yield from leaves(e.a)
        yield from leaves(e.b)
    elif isinstance(e, U):
        yield from leaves(e.a)
    elif isinstance(e, Rand):
        yield from leaves(e.a)
        yield from leaves(e.b)
    elif isinstance(e, Get):
        yield from leaves(e.var)
        for a in e.args:
            yield from leaves(a)
    else:
        yield e


