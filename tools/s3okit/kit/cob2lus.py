def infer_kinds(u, sig):
    """Fixed point over assignments and call args: which variables hold radians, which hold piece numbers."""
    fns = u.fns

    def key(fname, v):
        return ('s', v.i) if v.k == 's' else ('l', fname, v.i)

    # seeds
    for name, f in fns.items():
        info = sig.get(name)
        if not info:
            continue
        for i in info.get('rad', ()):
            u.rad_kind.add(('l', name, i))
        for i in info.get('piece', ()):
            u.piece_kind.add(('l', name, i))

    def rad_expr(fname, e):
        if isinstance(e, V):
            return key(fname, e) in u.rad_kind
        if isinstance(e, B) and e.op in ('add', 'sub'):
            return rad_expr(fname, e.a) or rad_expr(fname, e.b)
        if isinstance(e, B) and e.op in ('mul', 'div'):
            return rad_expr(fname, e.a)
        return False

    changed = True
    while changed:
        changed = False
        for name, f in fns.items():
            for s in walk(f.body):
                if s.kind == 'assign':
                    k = key(name, s.var)
                    if rad_expr(name, s.e) and k not in u.rad_kind:
                        u.rad_kind.add(k); changed = True
                elif s.kind in ('call', 'start'):
                    for i, a in enumerate(s.args):
                        k = ('l', s.fn, i)
                        if rad_expr(name, a) and k not in u.rad_kind:
                            u.rad_kind.add(k); changed = True
    both = u.rad_kind & u.piece_kind
    if both:
        raise Unsupported(f'variables typed both radians and piece: {sorted(map(str, both))}')


def blocking_fns(u):
    block = set()
    changed = True
    while changed:
        changed = False
        for name, f in u.fns.items():
            if name in block:
                continue
            for s in walk(f.body):
                if s.kind in ('sleep', 'waitturn', 'waitmove', 'setmask') or (s.kind == 'call' and s.fn in block):
                    block.add(name); changed = True
                    break
    return block


def bits(v):
    return [1 << i for i in range(32) if v & (1 << i)]


def split_weapon_signals(u, aim_fns):
    """Give each weapon its own aim signal and every restore thread shared by weapons its own too. Returns the mask rewrite:
    u.sig_names and the replacement of signal/setmask constants per function."""
    # weapon -> set of signal bits used by its aim function (direct, or through a function it calls)
    def closure(name, seen):
        if name in seen:
            return seen
        seen.add(name)
        for s in walk(u.fns[name].body):
            if s.kind == 'call':
                closure(s.fn, seen)
        return seen

    aim_sets = {}
    for w, name in aim_fns.items():
        aim_sets[w] = closure(name, set())

    usage = {}                  # bit -> set of weapons whose aim uses it
    for w, names in aim_sets.items():
        for n in names:
            for s in walk(u.fns[n].body):
                if s.kind in ('signal', 'setmask'):
                    if not isinstance(s.e, C):
                        raise Unsupported(f'{n}: runtime signal mask')
                    for b in bits(s.e.v):
                        usage.setdefault(b, set()).add(w)
    # restore threads: functions started from aim functions of more than one weapon
    started = {}
    for w, names in aim_sets.items():
        for n in names:
            for s in walk(u.fns[n].body):
                if s.kind == 'start' and s.fn.lower() != 'smokeunit':
                    started.setdefault(s.fn, set()).add(w)
    shared_threads = {f for f, ws in started.items() if len(ws) > 1}
    shared_bits = {b for b, ws in usage.items() if len(ws) > 1}
    if not shared_bits and not shared_threads:
        return {}
    # a function called (not started) by two weapons' aims and using the shared bits can't be separated automatically
    for n in set.union(*aim_sets.values()):
        owners = [w for w, names in aim_sets.items() if n in names]
        if len(owners) > 1:
            for s in walk(u.fns[n].body):
                if s.kind in ('setmask',) and isinstance(s.e, C) and set(bits(s.e.v)) & shared_bits:
                    raise Unsupported(f'{n}: sets a shared aim signal and is called by the aims of weapons {owners}')
    return {'bits': shared_bits, 'threads': shared_threads, 'aim_sets': aim_sets}


def lint_self_signal(u):
    """COB: a thread whose own mask matches its Signal dies. Lua: it continues."""
    for name, f in u.fns.items():
        mask = 0
        for s in walk(f.body):
            if s.kind == 'setmask' and isinstance(s.e, C):
                mask = s.e.v
            elif s.kind == 'signal' and isinstance(s.e, C) and (mask & s.e.v):
                u.warn(f'{name}: signals its own mask {s.e.v}: dies in COB, continues in Lua')


