def weapon_callin(lname):
    m = re.match(r'(aimfrom|aim|query|fire|shot|endburst|blockshot|targetweight)(primary|secondary|tertiary|weapon(\d+)|(\d+))$', lname)
    if not m:
        return None
    w = WNAMES.get(m.group(2)) or int(m.group(3) or m.group(4))
    return m.group(1), w


