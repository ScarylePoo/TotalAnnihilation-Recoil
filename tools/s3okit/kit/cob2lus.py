def fmt_num(x, digits):
    s = f'{round(x, digits):.{digits}f}'.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


def ang_literal(v):
    if v == 0:
        return '0'
    deg = v * 360.0 / 65536
    s = fmt_num(deg, 2)
    if s == '0':
        s = fmt_num(deg, 5)
    return f'rad({s})'


def lin_literal(v):
    return fmt_num(v / 65536.0, 3) if abs(v) >= 66 else fmt_num(v / 65536.0, 5)


class Emit:
    """Turn one unit's IR into Lua text."""

    def __init__(self, u):
        self.u = u
        self.cur = None             # current Fn
        self.need = set()           # helpers: rad, floor, COB2RAD, RAD2COB, Blow
        self.pieces = []
        self.explode_consts = {}

    # ---- naming
    def piece(self, i):
        u = self.u
        if not (0 <= i < len(u.pieces)):
            raise Unsupported(f'{self.cur.name if self.cur else "?"}: piece index {i} out of range')
        n = u.pieces[i]
        if n not in u.model:
            raise Unsupported(f'piece {n} used by {self.cur.name if self.cur else "?"} is not in the model')
        if n not in self.pieces:
            self.pieces.append(n)
        return self.pname(n)

    @staticmethod
    def valid_id(n):
        return re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', n) is not None

    def pname(self, n):
        if n in RESERVED or not self.valid_id(n) or n in self.u.fn_names.values() or n in self.u.taken_vars:
            return 'p_' + re.sub(r'\W', '_', n)
        return n

    def var(self, v):
        if v.k == 's':
            return self.u.static_names.get(v.i, f's{v.i}')
        return self.u.local_names.get((self.cur.name, v.i), f'l{v.i}')

    def key(self, v):
        return ('s', v.i) if v.k == 's' else ('l', self.cur.name, v.i)

    # ---- expression typing
    def is_rad(self, e):
        if isinstance(e, V):
            return self.key(e) in self.u.rad_kind
        if isinstance(e, B) and e.op in ('add', 'sub', 'mul', 'div'):
            return self.is_rad(e.a) or self.is_rad(e.b)
        if isinstance(e, U) and e.op == 'neg':
            return self.is_rad(e.a)
        return False

    @staticmethod
    def is_bool(e):
        return (isinstance(e, B) and e.op in ('lt', 'le', 'gt', 'ge', 'eq', 'ne', 'land', 'lor', 'lxor')) or (isinstance(e, U) and e.op == 'lnot')

    PREC = {'or': 1, 'and': 2, '<': 3, '<=': 3, '>': 3, '>=': 3, '==': 3, '~=': 3, '+': 5, '-': 5, '*': 6, '/': 6, '%': 6}

    def paren(self, s, prec, need):
        return f'({s})' if prec < need else s

    # returns (text, precedence); atoms 10
    def num(self, e):
        """Lua number holding the COB integer value"""
        if isinstance(e, C):
            return str(e.v), 10
        if isinstance(e, V):
            t = self.var(e)
            if self.key(e) in self.u.rad_kind:
                self.need.add('RAD2COB')
                return f'{t} * RAD2COB', 6
            return t, 10
        if isinstance(e, Rand):
            return f'math.random({self.num(e.a)[0]}, {self.num(e.b)[0]})', 10
        if isinstance(e, Get):
            return self.get(e), 10
        if self.is_bool(e):
            return f'{self.cond(e)} and 1 or 0', 1
        if isinstance(e, B):
            if e.op in ('and', 'or', 'xor'):
                raise Unsupported(f'{self.cur.name}: runtime bitwise {e.op}')
            op = BINOPS[e.op]
            if self.is_rad(e):
                t, p = self.rad(e)
                self.need.add('RAD2COB')
                return f'{self.paren(t, p, 6)} * RAD2COB', 6
            pr = self.PREC[op]
            a, pa = self.num(e.a)
            b, pb = self.num(e.b)
            text = f'{self.paren(a, pa, pr)} {op} {self.paren(b, pb, pr + 1)}'
            if e.op == 'div':
                self.need.add('floor')
                return f'floor({text})', 10
            if e.op == 'mod':
                return text, pr
            return text, pr
        if isinstance(e, U):
            if e.op == 'not':
                raise Unsupported(f'{self.cur.name}: runtime bitwise not')
        raise Unsupported(f'{self.cur.name}: cannot express {e}')

    def rad(self, e):
        """Lua number in radians"""
        if isinstance(e, C):
            if e.v == 0:
                return '0', 10
            self.need.add('rad')
            return ang_literal(e.v), 10
        if isinstance(e, V) and self.key(e) in self.u.rad_kind:
            return self.var(e), 10
        if isinstance(e, B) and e.op in ('add', 'sub'):
            if self.is_rad(e) or isinstance(e.a, C) or isinstance(e.b, C):
                op = BINOPS[e.op]
                pr = self.PREC[op]
                if e.op == 'sub' and isinstance(e.a, C) and e.a.v == 0:
                    b, pb = self.rad(e.b)
                    return f'-{self.paren(b, pb, 7)}', 7
                a, pa = self.rad(e.a)
                b, pb = self.rad(e.b)
                return f'{self.paren(a, pa, pr)} {op} {self.paren(b, pb, pr + 1)}', pr
        if isinstance(e, B) and e.op in ('mul', 'div'):
            op = BINOPS[e.op]
            if self.is_rad(e.a) and not self.is_rad(e.b):
                a, pa = self.rad(e.a)
                b, pb = self.num(e.b)
                return f'{self.paren(a, pa, 6)} {op} {self.paren(b, pb, 7)}', 6
            if e.op == 'mul' and self.is_rad(e.b) and not self.is_rad(e.a):
                a, pa = self.num(e.a)
                b, pb = self.rad(e.b)
                return f'{self.paren(a, pa, 6)} {op} {self.paren(b, pb, 7)}', 6
        if isinstance(e, B) and self.is_rad(e):
            # radians on both sides of a product or a quotient: no unit makes sense, keep the value
            op = BINOPS[e.op]
            a, pa = self.rad(e.a)
            b, pb = self.rad(e.b)
            self.u.warn(f'{self.cur.name}: {e.op} of two angles')
            return f'{self.paren(a, pa, 6)} {op} {self.paren(b, pb, 7)}', 6
        t, p = self.num(e)
        self.need.add('COB2RAD')
        return f'{self.paren(t, p, 6)} * COB2RAD', 6

    def lin(self, e):
        if isinstance(e, C):
            return lin_literal(e.v), 10
        t, p = self.num(e)
        return f'{self.paren(t, p, 6)} / 65536', 6

    def neg(self, e, conv):
        """-e via conv (rad or lin), folding constants"""
        if isinstance(e, C):
            return conv(C(-e.v))
        if isinstance(e, B) and e.op == 'sub' and isinstance(e.a, C) and e.a.v == 0:
            return conv(e.b)
        t, p = conv(e)
        return f'-{self.paren(t, p, 7)}', 7

    def cond(self, e):
        """Lua boolean"""
        if isinstance(e, C):
            return 'true' if e.v else 'false'
        if isinstance(e, B) and e.op in ('lt', 'le', 'gt', 'ge', 'eq', 'ne'):
            op = BINOPS[e.op]
            conv = self.rad if (self.is_rad(e.a) or self.is_rad(e.b)) else self.num
            a, pa = conv(e.a)
            b, pb = conv(e.b)
            return f'{self.paren(a, pa, 4)} {op} {self.paren(b, pb, 4)}'
        if isinstance(e, B) and e.op in ('land', 'lor'):
            op = BINOPS[e.op]
            a, b = self.cond(e.a), self.cond(e.b)
            wrap = lambda s, x: f'({s})' if (self.is_bool(x) and isinstance(x, B) and x.op in ('land', 'lor') and x.op != e.op) else s
            return f'{wrap(a, e.a)} {op} {wrap(b, e.b)}'
        if isinstance(e, B) and e.op == 'lxor':
            return f'({self.cond(e.a)}) ~= ({self.cond(e.b)})'
        if isinstance(e, U) and e.op == 'lnot':
            if self.is_bool(e.a):
                return f'not ({self.cond(e.a)})'
            t, p = self.num(e.a)
            return f'{self.paren(t, p, 4)} == 0'
        t, p = self.num(e)
        return f'{self.paren(t, p, 4)} ~= 0'

    def get(self, e):
        if not isinstance(e.var, C):
            raise Unsupported(f'{self.cur.name}: get with a runtime variable number')
        args = list(e.args)
        while args and isinstance(args[-1], C) and args[-1].v == 0:
            args.pop()
        texts = []
        vn = e.var.v
        for i, a in enumerate(args):
            if vn in (7, 8) and i == 0:
                # the COB value takes a 0-based script piece index, not Lua's 1-based number
                texts.append(f'{self.piece_value(a)} - 1')
            else:
                texts.append(self.num(a)[0])
        name = self.cobval(vn)
        return f'GetUnitValue({", ".join([name] + texts)})'

    def cobval(self, vn):
        n = COB_NAMED.get(vn)
        if n is None:
            raise Unsupported(f'{self.cur.name}: unknown COB value {vn}')
        if n in COB_TABLE:
            return f'COB.{n}'
        self.u.num_consts[n] = vn
        return n

    def piece_value(self, e):
        if isinstance(e, C):
            if e.v == -1:
                return '-1'
            return self.piece(e.v)
        if isinstance(e, V) and self.key(e) in self.u.piece_kind:
            return self.var(e)
        # BOS could use a counter as a piece number (`piecenum = gun`): COB piece numbers go through a table
        self.need.add('COB_PIECE')
        return f'COB_PIECE[{self.num(e)[0]}]'

    def attach_piece(self, e):
        # COB attaches to piece -1 to hide the unit; Lua's numbers are 1-based, so that is 0 there
        if isinstance(e, C) and e.v < 0:
            return '0'
        return self.piece_value(e)

    # ---- statements
    def explode_flags(self, e):
        if not isinstance(e, C):
            raise Unsupported(f'{self.cur.name}: runtime explode flags')
        names = [n for b, n in EXPLODE_BITS if e.v & b]
        return ' + '.join('SFX.' + n for n in names) if names else '0'

    def is_empty_piece(self, i):
        n = self.u.pieces[i] if 0 <= i < len(self.u.pieces) else None
        return n in self.u.model and self.u.model[n][0] == 0

    def has_piece(self, i):
        return 0 <= i < len(self.u.pieces) and self.u.pieces[i] in self.u.model

    def block(self, body, ind, ret=None):
        out = []
        i = 0
        while i < len(body):
            s = body[i]
            if s.kind == 'explode' and self.has_piece(s.p):
                # consecutive explosions with the same flags read as one line
                j = i
                group = []
                flags = self.explode_flags(s.e)
                while j < len(body) and body[j].kind == 'explode' and self.has_piece(body[j].p) and self.explode_flags(body[j].e) == flags:
                    group.append(self.piece(body[j].p))
                    j += 1
                if len(group) == 1:
                    out.append(f'{ind}Explode({group[0]}, {flags})')
                else:
                    self.need.add('Blow')
                    out.extend(self.wrap(f'{ind}Blow({{', group, f'}}, {flags})'))
                i = j
                continue
            # Killed: `corpsetype = N ... return` becomes `... return N`
            out.extend(self.stmt(s, ind, ret))
            i += 1
        return out

    @staticmethod
    def wrap(head, items, tail, width=118):
        lines, cur = [], head
        indent = re.match(r'\s*', head).group(0) + '\t'
        for k, it in enumerate(items):
            piece = it + (', ' if k < len(items) - 1 else '')
            if len(cur) + len(piece) > width and cur.strip():
                lines.append(cur.rstrip())
                cur = indent
            cur += piece
        lines.append(cur + tail)
        return lines

    def stmt(self, s, ind, ret):
        k = s.kind
        u = self.u
        if k == 'assign':
            if self.key(s.var) in u.piece_kind:
                val = self.piece_value(s.e)
            elif self.key(s.var) in u.rad_kind:
                val = self.rad(s.e)[0]
            elif self.is_bool(s.e):
                val = f'{self.cond(s.e)} and 1 or 0'
            else:
                val = self.num(s.e)[0]
            return [f'{ind}{self.var(s.var)} = {val}']
        if k in ('turn', 'move', 'spin', 'stopspin', 'waitturn', 'waitmove', 'show', 'hide', 'emit', 'explode') and not self.has_piece(s.p):
            u.warn(f'{self.cur.name}: dropped {k} on {u.pieces[s.p] if 0 <= s.p < len(u.pieces) else s.p}: not in the model')
            return []
        if k == 'turn':
            if s.speed is not None and isinstance(s.speed, C) and s.speed.v == 0:
                return []
            dest = self.neg(s.dest, self.rad)[0] if s.ax == 2 else self.rad(s.dest)[0]
            if s.speed is None:
                return [f'{ind}Turn({self.piece(s.p)}, {AXIS[s.ax]}, {dest})']
            if not isinstance(s.speed, C):
                u.warn(f'{self.cur.name}: runtime turn speed (0 would snap in Lua, does nothing in COB)')
            return [f'{ind}Turn({self.piece(s.p)}, {AXIS[s.ax]}, {dest}, {self.rad(s.speed)[0]})']
        if k == 'move':
            if s.speed is not None and isinstance(s.speed, C) and s.speed.v == 0:
                return []
            dest = self.neg(s.dest, self.lin)[0] if s.ax == 0 else self.lin(s.dest)[0]
            if s.speed is None:
                return [f'{ind}Move({self.piece(s.p)}, {AXIS[s.ax]}, {dest})']
            if not isinstance(s.speed, C):
                u.warn(f'{self.cur.name}: runtime move speed (0 would snap in Lua, does nothing in COB)')
            return [f'{ind}Move({self.piece(s.p)}, {AXIS[s.ax]}, {dest}, {self.lin(s.speed)[0]})']
        if k == 'spin':
            speed = self.neg(s.speed, self.rad)[0] if s.ax == 2 else self.rad(s.speed)[0]
            accel = self.rad(s.accel)[0]
            return [f'{ind}Spin({self.piece(s.p)}, {AXIS[s.ax]}, {speed}' + (f', {accel})' if accel != '0' else ')')]
        if k == 'stopspin':
            decel = self.rad(s.decel)[0]
            return [f'{ind}StopSpin({self.piece(s.p)}, {AXIS[s.ax]}' + (f', {decel})' if decel != '0' else ')')]
        if k == 'waitturn':
            return [f'{ind}WaitForTurn({self.piece(s.p)}, {AXIS[s.ax]})']
        if k == 'waitmove':
            return [f'{ind}WaitForMove({self.piece(s.p)}, {AXIS[s.ax]})']
        if k == 'sleep':
            return [f'{ind}Sleep({self.num(s.e)[0]})']
        if k in ('show', 'hide'):
            if self.is_empty_piece(s.p):
                return []           # flare pieces have no geometry since the remodel
            return [f'{ind}{"Show" if k == "show" else "Hide"}({self.piece(s.p)})']
        if k == 'emit':
            return [f'{ind}EmitSfx({self.piece(s.p)}, {self.num(s.e)[0]})']
        if k == 'explode':
            return [f'{ind}Explode({self.piece(s.p)}, {self.explode_flags(s.e)})']
        if k == 'signal':
            return [f'{ind}Signal({self.mask(s.e)})']
        if k == 'setmask':
            return [f'{ind}SetSignalMask({self.mask(s.e)})']
        if k == 'setval':
            if not isinstance(s.var, C):
                raise Unsupported(f'{self.cur.name}: set with a runtime variable number')
            val = f'{self.cond(s.e)} and 1 or 0' if self.is_bool(s.e) else self.num(s.e)[0]
            if s.var.v == 7 or s.var.v == 8:
                raise Unsupported(f'{self.cur.name}: set of a piece value')
            return [f'{ind}SetUnitValue({self.cobval(s.var.v)}, {val})'.replace(' --[[', ' --[[')]
        if k == 'attach':
            self.need.add('AttachUnit')
            return [f'{ind}AttachUnit({self.attach_piece(s.piece)}, {self.num(s.unit)[0]})']
        if k == 'drop':
            self.need.add('DropUnit')
            return [f'{ind}DropUnit({self.num(s.unit)[0]})']
        if k == 'call':
            return [f'{ind}{self.fn(s.fn)}({self.call_args(s)})']
        if k == 'start':
            if s.fn.lower() == 'smokeunit':
                return [f'{ind}StartThread(SmokeUnit, {{{", ".join(self.smoke_pieces(s.fn))}}})']
            a = self.call_args(s)
            return [f'{ind}StartThread({self.fn(s.fn)}{", " + a if a else ""})']
        if k == 'return':
            return ret(self, s, ind) if ret else [f'{ind}return']
        if k == 'if':
            out = [f'{ind}if {self.cond(s.cond)} then']
            then = self.block(s.then, ind + '\t', ret)
            out += then
            other = s.other
            while len(other) == 1 and other[0].kind == 'if':
                out.append(f'{ind}elseif {self.cond(other[0].cond)} then')
                out += self.block(other[0].then, ind + '\t', ret)
                other = other[0].other
            if other:
                out.append(f'{ind}else')
                out += self.block(other, ind + '\t', ret)
            out.append(f'{ind}end')
            return out
        if k == 'while':
            out = [f'{ind}while {self.cond(s.cond)} do']
            body = self.block(s.body, ind + '\t', ret)
            # a Lua `return` must be the last statement in a block; always true here since regions stop at a return
            out += body
            out.append(f'{ind}end')
            return out
        raise Unsupported(f'{self.cur.name}: statement {k}')

    def call_args(self, s):
        g = self.u.fns[s.fn]
        vals = []
        for i in range(g.nargs):
            if i < len(s.args):
                a = s.args[i]
                kk = ('l', s.fn, i)
                if kk in self.u.piece_kind:
                    vals.append(self.piece_value(a))
                elif kk in self.u.rad_kind:
                    vals.append(self.rad(a)[0])
                elif self.is_bool(a):
                    vals.append(f'{self.cond(a)} and 1 or 0')
                else:
                    vals.append(self.num(a)[0])
            else:
                vals.append('0')
        return ', '.join(vals)

    def mask(self, e):
        if not isinstance(e, (C, tuple, str)):
            raise Unsupported(f'{self.cur.name}: runtime signal mask')
        if isinstance(e, C):
            return self.u.sig_names.get(e.v, str(e.v))
        return str(e)

    def fn(self, name):
        return self.u.fn_names.get(name, name)

    def smoke_pieces(self, fn):
        names = []
        for s in walk(self.u.fns[fn].body):
            if s.kind == 'emit' and self.has_piece(s.p):
                p = self.piece(s.p)
                if p not in names:
                    names.append(p)
        if not names:
            raise Unsupported('SmokeUnit emits from no known piece')
        return names


