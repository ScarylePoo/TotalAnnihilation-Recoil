class Unit:
    def __init__(self, stem, cobpath, model_pieces):
        self.stem, self.model = stem, model_pieces
        self.pieces, self.names, self.starts, self.ins, self.nstatic, self.codelen = decode(cobpath)
        self.lname = {n.lower(): n for n in self.names}
        self.fns = {}
        self.warnings = []
        self.piece_kind = set()      # variables holding a piece number
        self.rad_kind = set()        # variables holding radians
        self.static_names = {}
        self.local_names = {}
        self.sig_names = {}
        self.fn_names = {}
        self.num_consts = {}
        self.taken_vars = set()      # local and static names: a piece global must not be shadowed by them

    def warn(self, msg):
        self.warnings.append(msg)

    # ---- load reachable functions
    def load(self, name):
        if name in self.fns:
            return self.fns[name]
        i = self.names.index(name)
        start = self.starts[i]
        end = script_end(start, self.starts, self.codelen)
        if start >= self.codelen or start not in self.ins or (i + 1 < len(self.starts) and self.starts[i + 1] == start):
            f = Fn(name, [], 0)         # zero length (some compilers do this for an empty function)
        else:
            d = Decompiler(self.ins, self.names, self.starts, name)
            body = d.region(start, end)
            f = Fn(name, body, max(d.nclv, d.maxlocal + 1))
        self.fns[name] = f
        for s in walk(f.body):
            if s.kind in ('call', 'start'):
                g = self.load(s.fn)
                g.called = True
                g.nargs = max(g.nargs, len(s.args))
                g.nslots = max(g.nslots, g.nargs)
        return f

    def callins(self):
        """COB function name -> descriptor (kind, weapon)"""
        out = {}
        for ln, n in self.lname.items():
            wc = weapon_callin(ln)
            if wc:
                out[n] = wc
            elif ln in SIMPLE_CALLINS or ln in ('killed', 'sweetspot', 'querynanopiece', 'querybuildinfo', 'querylandingpad', 'hitbyweapon',
                                                'hitbyweaponid', 'rockunit', 'setsfxoccupy', 'setmaxreloadtime', 'setspeed', 'setdirection',
                                                'begintransport', 'querytransport', 'transportpickup', 'transportdrop', 'targetcleared',
                                                'moverate0', 'moverate1', 'moverate2', 'moverate3'):
                out[n] = (ln, None)
        return out


def load_model_pieces(stem):
    p = os.path.join(OBJECTS, stem + '.s3o')
    if not os.path.exists(p):
        for f in os.listdir(OBJECTS):
            if f.lower() == (stem + '.s3o').lower():
                p = os.path.join(OBJECTS, f)
                break
        else:
            raise Unsupported(f'no model objects3d/{stem}.s3o')
    return {x['name'].lower(): (len(x['idx']) // 3, x['name']) for x in s3o.read(p)['pieces']}


