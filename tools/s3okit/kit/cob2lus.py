def build_signature(u):
    """{cob fn name: dict(args=[names], rad=[slots], piece=[slots])} for callins; internal functions get a0, a1..."""
    sig = {}
    ci = u.callins()
    for n, (kind, w) in ci.items():
        if kind == 'aim':
            sig[n] = dict(args=['heading', 'pitch'], rad=[0, 1])
        elif kind in ('aimfrom', 'query'):
            sig[n] = dict(args=['piecenum'], piece=[0])
        elif kind == 'sweetspot' or kind in ('querynanopiece', 'querybuildinfo'):
            sig[n] = dict(args=['piecenum'], piece=[0])
        elif kind == 'killed':
            sig[n] = dict(args=['severity', 'corpsetype'])
        elif kind in ('hitbyweapon', 'rockunit'):
            sig[n] = dict(args=['anglex', 'anglez'])
        elif kind == 'setsfxoccupy':
            sig[n] = dict(args=['terrain'])
        elif kind == 'setmaxreloadtime':
            sig[n] = dict(args=['reload'])
        elif kind == 'setspeed':
            sig[n] = dict(args=['speed'])
        elif kind == 'setdirection':
            sig[n] = dict(args=['heading'], rad=[0])
        elif kind == 'startbuilding':
            sig[n] = dict(args=['heading', 'pitch'], rad=[0, 1])
        elif kind == 'querytransport':
            sig[n] = dict(args=['piecenum', 'height'], piece=[0])
        elif kind == 'begintransport':
            sig[n] = dict(args=['height'])
        elif kind == 'transportpickup':
            sig[n] = dict(args=['unitid'])
        elif kind == 'transportdrop':
            sig[n] = dict(args=['unitid', 'pos'])
        elif kind == 'querylandingpad':
            sig[n] = dict(args=[f'pad{i + 1}' for i in range(max(1, u.fns[n].nslots if n in u.fns else 1))],
                          piece=list(range(max(1, u.fns[n].nslots if n in u.fns else 1))))
    return sig


def stem_title(stem):
    return stem.rsplit('_', 1)[-1]


def transpile(stem, cobpath, overrides=None):
    model = load_model_pieces(stem)
    u = Unit(stem, cobpath, model)
    ci = u.callins()
    # reachable functions from engine callins only. TargetCleared is not one: the engine never calls it.
    deftext = open(os.path.join(UNITS, stem + '.lua'), encoding='latin-1').read()
    wind = re.search(r'windgenerator\s*=\s*[1-9]', deftext, re.I) is not None
    ext = re.search(r'extractsmetal\s*=\s*0*\.?0*[1-9]', deftext, re.I) is not None
    for n, (kind, w) in list(ci.items()):
        if kind == 'targetcleared' or (kind == 'setspeed' and not (wind or ext)) or (kind == 'setdirection' and not wind):
            del ci[n]
            if kind == 'setspeed':
                u.warn('SetSpeed dropped: neither a wind generator nor an extractor')
            continue
        u.load(n)
    if ext and 'go' in u.lname:
        u.load(u.lname['go']).called = True
    return Generator(u, ci, dict(overrides or {}, wind=wind, ext=ext)).run()


class Generator:
    def __init__(self, u, ci, ov):
        self.u, self.ci, self.ov = u, ci, ov
        self.e = Emit(u)

    # ---- pattern recognition and names
    def by_kind(self, kind):
        for n, (k, w) in self.ci.items():
            if k == kind:
                return n
        return None

    def name_statics(self):
        u = self.u
        names = {}
        f = self.by_kind('setmaxreloadtime')
        if f and f in u.fns:
            for s in walk(u.fns[f].body):
                if s.kind == 'assign' and s.var.k == 's' and any(isinstance(x, V) and x.k == 'l' for x in leaves(s.e)):
                    names.setdefault(s.var.i, 'restore_delay')
        init = next((n for n in u.fns if n.lower() == 'initstate'), None)
        if init:
            order = ('state_desired', 'state_changing')
            k = 0
            for s in u.fns[init].body:
                if s.kind == 'assign' and s.var.k == 's' and k < 2:
                    names.setdefault(s.var.i, order[k])
                    k += 1
        for fn_kind, val in (('startmoving', 1), ('stopmoving', 0)):
            f = self.by_kind(fn_kind)
            if f and f in u.fns:
                for s in u.fns[f].body:
                    if s.kind == 'assign' and s.var.k == 's' and isinstance(s.e, C) and s.e.v == val:
                        names.setdefault(s.var.i, 'moving')
        # a static read by a QueryN and assigned in the matching FireN selects the barrel
        for n, (k, w) in self.ci.items():
            if k != 'query':
                continue
            read = {leaf.i for s in walk(u.fns[n].body) for _, e in exprs_of(s) for leaf in leaves(e) if isinstance(leaf, V) and leaf.k == 's'}
            for m, (k2, w2) in self.ci.items():
                if k2 == 'fire' and w2 == w:
                    for s in walk(u.fns[m].body):
                        if s.kind == 'assign' and s.var.k == 's' and s.var.i in read and s.var.i not in names:
                            names[s.var.i] = 'gun_index' if 'gun_index' not in names.values() else f'gun_index{w}'
        u.static_names = names

    def name_locals(self, sig):
        u = self.u
        for name, f in u.fns.items():
            info = sig.get(name, {})
            for i, a in enumerate(info.get('args', [])):
                u.local_names[(name, i)] = a
            if name.lower() == 'requeststate':
                u.local_names[(name, 0)], u.local_names[(name, 1)] = 'requested', 'actual'
            for i in range(f.nslots):
                u.local_names.setdefault((name, i), f'a{i}' if i < f.nargs else f'l{i}')

    def name_fns(self):
        u = self.u
        taken = set(u.pieces) | RESERVED
        for name in u.fns:
            nn = re.sub(r'\W', '_', name)
            if nn in taken or nn.lower() in LUA_KEYWORDS:
                nn = 'fn_' + nn
            taken.add(nn)
            u.fn_names[name] = nn

    # ---- signals
    def rewrite_signals(self, aim_fns):
        """Rename mask constants; split shared ones per weapon. Rewrites signal/setmask statements' e into text."""
        u = self.u
        split = split_weapon_signals(u, aim_fns)
        shared_bits = split.get('bits', set()) if split else set()
        threads = split.get('threads', set()) if split else set()
        aim_sets = split.get('aim_sets', {}) if split else {}

        # collect all bits
        allbits = set()
        for name, f in u.fns.items():
            for s in walk(f.body):
                if s.kind in ('signal', 'setmask'):
                    if not isinstance(s.e, C):
                        raise Unsupported(f'{name}: runtime signal mask')
                    allbits |= set(bits(s.e.v))

        constants = []          # (name, value)
        next_bit = [1]

        def alloc(nm):
            v = next_bit[0]
            next_bit[0] <<= 1
            if v > (1 << 23):
                raise Unsupported('more than 24 signal bits')
            constants.append((nm, v))
            return nm

        # names for ordinary bits
        bit_name = {}
        for b in sorted(allbits):
            if b in shared_bits:
                continue
            bit_name[b] = None
        # which function uses a bit, for a readable name
        def nice(b):
            users = [n for n, f in u.fns.items() for s in walk(f.body) if s.kind in ('signal', 'setmask') and isinstance(s.e, C) and s.e.v & b]
            kinds = {self.ci.get(n, (n.lower(), None))[0] for n in users}
            aims = sorted({self.ci[n][1] for n in users if n in self.ci and self.ci[n][0] == 'aim'})
            if aims:
                return 'SIG_AIM' + (str(aims[0]) if len(aims) == 1 and len(aim_fns) > 1 else '')
            if kinds & {'startmoving', 'stopmoving'}:
                return 'SIG_MOVE'
            if any('restore' in k for k in kinds):
                return 'SIG_RESTORE'
            if kinds & {'hitbyweapon', 'rockunit'}:
                return 'SIG_HIT'
            return 'SIG_' + re.sub(r'\W', '_', users[0]).upper() if users else f'SIG_{b}'

        used_names = set()
        for b in list(bit_name):
            nm = nice(b)
            base, k = nm, 2
            while nm in used_names:
                nm = f'{base}_{k}'
                k += 1
            used_names.add(nm)
            bit_name[b] = alloc(nm)

        weapon_bit = {}         # (bit, weapon) -> name
        for b in sorted(shared_bits):
            for w in sorted(aim_fns):
                nm = f'SIG_AIM{w}'
                base, k = nm, 2
                while nm in used_names:
                    nm = f'{base}_{k}'
                    k += 1
                used_names.add(nm)
                weapon_bit[(b, w)] = alloc(nm)
        restore_name = None
        if threads:
            restore_name = 'SIG_RESTORE'
            k = 2
            while restore_name in used_names:
                restore_name = f'SIG_RESTORE_{k}'
                k += 1
            used_names.add(restore_name)
            alloc(restore_name)

        owner = {}              # fn -> weapon it runs for (aim closure)
        for w, names in aim_sets.items():
            for n in names:
                owner.setdefault(n, set()).add(w)

        def render(name, bitsv):
            parts = []
            for b in bits(bitsv):
                if b in shared_bits:
                    wset = owner.get(name)
                    if name in threads:
                        parts.append(restore_name)
                    elif wset and len(wset) == 1:
                        parts.append(weapon_bit[(b, next(iter(wset)))])
                    else:
                        parts.extend(weapon_bit[(b, w)] for w in sorted(aim_fns))
                else:
                    parts.append(bit_name[b])
            seen = []
            for p in parts:
                if p not in seen:
                    seen.append(p)
            return ' + '.join(seen) if seen else '0'

        def rewrite(body, name):
            for s in walk(body):
                if s.kind in ('signal', 'setmask'):
                    s.f['e'] = render(name, s.e.v) if isinstance(s.e, C) else s.e

        for name, f in u.fns.items():
            rewrite(f.body, name)

        # restore threads: killed by any weapon's new aim, own mask
        if threads:
            for t in threads:
                fnb = u.fns[t].body
                body = [s for s in fnb if not (s.kind == 'setmask' or (s.kind == 'signal' and s.e == restore_name))]
                u.fns[t].body = [S('setmask', e=restore_name)] + body
            for w, name in aim_fns.items():
                body = u.fns[name].body
                u.fns[name].body = [S('signal', e=restore_name)] + body
        self.sig_constants = constants

    # ---- function text
    def locals_decl(self, f, skip):
        out = []
        for i in range(f.nslots):
            if i in skip:
                continue
            out.append(f'\tlocal {self.u.local_names[(f.name, i)]} = 0')
        return out

    def fn_body(self, f, ret=None, skip=(), ind='\t'):
        e = self.e
        e.cur = f
        body = e.block(f.body, ind, ret)
        if body and body[-1] == f'{ind}return':
            body.pop()              # void function: the COB's final `return 0` says nothing
        decl = self.locals_decl(f, set(skip))
        return decl + body

    def internal(self, f, block):
        args = [self.u.local_names[(f.name, i)] for i in range(f.nargs)]
        out = [f'local function {self.u.fn_names[f.name]}({", ".join(args)})']
        out += self.fn_body(f, ret=lambda em, s, ind: [f'{ind}return'], skip=range(f.nargs))
        out.append('end')
        return out

    def order_internals(self):
        """dependency order for local functions: callees first; a cycle gets a forward declaration"""
        u = self.u
        order, seen, cycle = [], set(), set()
        stack = []

        def visit(n):
            if n in seen:
                if n in stack:
                    cycle.add(n)
                return
            seen.add(n)
            stack.append(n)
            for s in walk(u.fns[n].body):
                if s.kind in ('call', 'start'):
                    if s.fn.lower() != 'smokeunit':
                        visit(s.fn)
            stack.pop()
            order.append(n)
        for n in u.fns:
            visit(n)
        return order, cycle

    def run(self):
        u, e, ci = self.u, self.e, self.ci
        sig = build_signature(u)
        self.name_statics()
        self.name_locals(sig)
        self.name_fns()
        u.taken_vars = set(u.local_names.values()) | set(u.static_names.values()) | {f's{i}' for i in range(u.nstatic)}

        aim_fns = {w: n for n, (k, w) in ci.items() if k == 'aim' and n in u.fns}
        weapons = sorted({w for n, (k, w) in ci.items() if w and k in ('aim', 'aimfrom', 'query', 'fire', 'shot', 'endburst')})
        for n, (k, w) in ci.items():
            if k in ('blockshot', 'targetweight'):
                raise Unsupported(f'{n}: BlockShot/TargetWeight not handled')
        infer_kinds(u, sig)
        lint_self_signal(u)
        self.rewrite_signals(aim_fns)
        block = blocking_fns(u)

        # ---- callins that are never reached by the engine in Lua are handled below; emit
        internals = set()       # functions referenced from other functions
        for f in u.fns.values():
            for s in walk(f.body):
                if s.kind in ('call', 'start') and s.fn.lower() != 'smokeunit':
                    internals.add(s.fn)
        if self.ov.get('ext') and 'go' in u.lname:
            internals.add(u.lname['go'])

        multi = len(weapons) > 1 or any(w != 1 for w in weapons)
        texts = []
        smoke = 'smokeunit' in u.lname and u.lname['smokeunit'] in u.fns

        def bool_ret(em, s, ind):
            if isinstance(s.e, C):
                return [f'{ind}return {"true" if s.e.v else "false"}']
            return [f'{ind}return {em.cond(s.e)}']

        out_after = []          # script.* definitions, after all local functions

        order, cycle = self.order_internals()
        need_forward = sorted(u.fn_names[n] for n in cycle)

        # internal functions first, including callins referenced internally (they keep COB's arg semantics)
        for n in order:
            if n not in internals or (smoke and n == u.lname['smokeunit']):
                continue
            f = u.fns[n]
            if cycle and n in cycle:
                t = self.internal(f, block)
                t[0] = t[0].replace('local function ', '').replace(f'{u.fn_names[n]}(', f'{u.fn_names[n]} = function(', 1)
                texts.append(t)
            else:
                texts.append(self.internal(f, block))

        # ---- plain callins
        def plain(fname, lua_name, threaded, lua_args=''):
            f = u.fns[fname]
            if fname in internals:
                # already a local function: forward to it
                ln = u.fn_names[fname]
                a = ', '.join(['0'] * f.nargs)
                if f.name in block and not threaded:
                    out_after.append([f'function script.{lua_name}({lua_args})', f'\tStartThread({ln}{", " + a if a else ""})', 'end'])
                else:
                    out_after.append([f'function script.{lua_name}({lua_args})', f'\t{ln}({a})', 'end'])
                return
            lines = self.fn_body(f, ret=lambda em, s, ind: [f'{ind}return'])
            if f.name in block and not threaded:
                ln = u.fn_names[fname]
                out_after.append([f'local function {ln}()'] + lines + ['end', '', f'function script.{lua_name}({lua_args})', f'\tStartThread({ln})', 'end'])
            else:
                out_after.append([f'function script.{lua_name}({lua_args})'] + lines + ['end'])

        for n, (k, w) in ci.items():
            if k == 'create':
                continue
            if k in SIMPLE_CALLINS and k not in ('startbuilding',):
                plain(n, SIMPLE_CALLINS[k], k in THREADED)

        # ---- Create: SetMaxReloadTime runs right after it in COB
        cr = self.by_kind('create')
        smr = self.by_kind('setmaxreloadtime')
        pre = []
        if smr and smr in u.fns and u.fns[smr].body:
            f = u.fns[smr]
            e.cur = f
            if smr in internals:
                raise Unsupported('SetMaxReloadTime is also called from the script')
            lines = self.fn_body(f, ret=lambda em, s, ind: [f'{ind}return'], skip=[0])
            texts.append([f'local function {u.fn_names[smr]}(reload)'] + lines + ['end'])
            pre = [f'\t{u.fn_names[smr]}(Spring.UnitScript.GetLongestReloadTime(unitID))']
        if cr:
            f = u.fns[cr]
            if cr in internals:
                raise Unsupported('Create is called from the script')
            lines = self.fn_body(f, ret=lambda em, s, ind: [f'{ind}return'])
            if pre and cr in block:
                # COB runs Create up to its first sleep, then SetMaxReloadTime
                out_after.insert(0, ['local function Create()'] + lines + ['end', '', 'function script.Create()', '\tStartThread(Create)'] + pre + ['end'])
            else:
                out_after.insert(0, ['function script.Create()'] + lines + pre + ['end'])

        # ---- StartBuilding: heading/pitch args if the COB declares them
        sb = self.by_kind('startbuilding')
        if sb:
            f = u.fns[sb]
            if sb in internals:
                raise Unsupported('StartBuilding is called from the script')
            lines = self.fn_body(f, ret=lambda em, s, ind: [f'{ind}return'], skip=[0, 1])
            # a factory's StartBuilding gets no args (COB: 0)
            pre_sb = [f'\t{v} = {v} or 0' for v in ('heading', 'pitch') if any(re.search(rf'\b{v}\b', ln) for ln in lines)]
            out_after.append(['function script.StartBuilding(heading, pitch)'] + pre_sb + lines + ['end'])

        # ---- by-reference piece queries
        for n, (k, w) in ci.items():
            if k in ('sweetspot', 'querynanopiece', 'querybuildinfo'):
                if n in block:
                    raise Unsupported(f'{n} can block')
                lua = {'sweetspot': 'SweetSpot', 'querynanopiece': 'QueryNanoPiece', 'querybuildinfo': 'QueryBuildInfo'}[k]
                out_after.append(self.piece_query(n, f'function script.{lua}()'))

        # ---- weapons
        names_w = {'aimfrom': 'AimFromWeapon', 'query': 'QueryWeapon', 'aim': 'AimWeapon', 'fire': 'FireWeapon', 'shot': 'Shot', 'endburst': 'EndBurst'}
        for w in weapons:
            for k, lua in names_w.items():
                n = next((m for m, (k2, w2) in ci.items() if k2 == k and w2 == w), None)
                if n is None:
                    if k == 'aim' and w == min(weapons):
                        # the gadget's per-weapon dispatch is only set up when AimWeapon1 exists
                        pass
                    continue
                sfx = str(w) if multi else ''
                if k in ('aimfrom', 'query'):
                    if n in block:
                        raise Unsupported(f'{n} can block')
                    a = f'num' if not multi else ''
                    out_after.append(self.piece_query(n, f'function script.{lua}{sfx}({a})'))
                elif k == 'aim':
                    if n in internals:
                        raise Unsupported(f'{n} is called from the script')
                    lines = self.fn_body(u.fns[n], ret=bool_ret, skip=[0, 1])
                    lines.extend(self.fall_through_false(u.fns[n]))
                    a = 'num, heading, pitch' if not multi else 'heading, pitch'
                    out_after.append([f'function script.{lua}{sfx}({a})'] + lines + ['end'])
                else:
                    if n in internals:
                        ln = u.fn_names[n]
                        lines = [f'\t{ln}()']
                    else:
                        lines = self.fn_body(u.fns[n], ret=lambda em, s, ind: [f'{ind}return'])
                    threaded = k == 'fire'
                    a = 'num' if not multi else ''
                    if n in block and not threaded and n not in internals:
                        ln = u.fn_names[n]
                        out_after.append([f'local function {ln}()'] + lines + ['end', '', f'function script.{lua}{sfx}({a})', f'\tStartThread({ln})', 'end'])
                    else:
                        out_after.append([f'function script.{lua}{sfx}({a})'] + lines + ['end'])
        # A weapon with no aim function can never fire, in COB as in Lua (bombs excepted: they ignore aim). Always ready instead;
        # the gadget's per-weapon dispatch also needs AimWeapon1 to exist.
        for w in (range(1, max(weapons) + 1) if weapons else ()):
            if w not in aim_fns:
                sfx, a = (str(w), 'heading, pitch') if multi else ('', 'num, heading, pitch')
                out_after.append([f'function script.AimWeapon{sfx}({a})', '\treturn true', 'end'])

        # ---- remaining special callins
        self.special_callins(out_after, block, internals)

        # ---- Killed
        kl = self.by_kind('killed')
        if kl:
            out_after.append(self.killed(kl))

        # ---- assemble
        lines = []
        hdr = [f'-- {stem_title(u.stem)} ({u.stem}): Lua unit script {GEN_TAG} from {u.stem}.COB.', ]
        # function bodies were rendered first: e.pieces is complete now
        old_groups = self.piece_lines()
        lines += old_groups
        if smoke:
            lines += ['', 'include "smokeunit.lua"']
        constants = []
        for api in ('AttachUnit', 'DropUnit'):
            if api in e.need:
                constants.append(f'local {api} = Spring.UnitScript.{api}')
        if 'rad' in e.need:
            constants.append('local rad = math.rad')
        if 'floor' in e.need:
            constants.append('local floor = math.floor')
        if 'COB2RAD' in e.need:
            constants.append('local COB2RAD = math.pi / 32768')
        if 'RAD2COB' in e.need:
            constants.append('local RAD2COB = 32768 / math.pi')
        for nm, v in sorted(u.num_consts.items()):
            constants.append(f'local {nm} = {v}')
        for nm, v in self.sig_constants:
            constants.append(f'local {nm} = {v}')
        statics = []
        used_statics = set()
        for f in u.fns.values():
            for s in walk(f.body):
                for _, ex in exprs_of(s):
                    if isinstance(ex, (C, V, B, U, Rand, Get)):
                        for leaf in leaves(ex):
                            if isinstance(leaf, V) and leaf.k == 's':
                                used_statics.add(leaf.i)
                if s.kind == 'assign' and s.var.k == 's':
                    used_statics.add(s.var.i)
        for i in sorted(used_statics):
            nm = u.static_names.get(i, f's{i}')
            init = '0'
            statics.append(f'local {nm} = {init}')
        if constants or statics:
            lines.append('')
            lines += constants + statics
        if need_forward:
            lines += ['', 'local ' + ', '.join(need_forward)]
        if 'COB_PIECE' in e.need:
            cand = self.cob_piece_candidates()
            for i, n in cand:
                e.cur = None
                e.piece(i)
            groups = self.piece_lines()
            lines[:len(old_groups)] = groups
            lines.append('')
            lines += self.e.wrap('local COB_PIECE = {', [f'[{i}] = {e.pname(n)}' for i, n in cand], '}')
        if 'Blow' in e.need:
            lines += ['', 'local function Blow(list, flags)', '\tfor _, p in ipairs(list) do Explode(p, flags) end', 'end']
        for t in texts + out_after:
            lines.append('')
            lines += t
        body = '\n'.join(lines) + '\n'
        return self.u, hdr, body

    def cob_piece_candidates(self):
        """COB piece numbers a counter can take, judged from what it is assigned and compared with; every piece if unclear"""
        u = self.u
        full = [(i, n) for i, n in enumerate(u.pieces) if n in u.model]
        statics = set()
        for f in u.fns.values():
            for s in walk(f.body):
                if s.kind == 'assign' and s.var.k == 'l' and ('l', f.name, s.var.i) in u.piece_kind:
                    if not (isinstance(s.e, V) and s.e.k == 's'):
                        if not isinstance(s.e, C):
                            return full
                    elif isinstance(s.e, V):
                        statics.add(s.e.i)
        vals = {0}

        def const_cmp(e):
            if isinstance(e, B) and e.op in ('eq', 'ne', 'lt', 'le', 'gt', 'ge'):
                for x, y in ((e.a, e.b), (e.b, e.a)):
                    if isinstance(x, V) and x.k == 's' and x.i in statics and isinstance(y, C):
                        vals.add(y.v)
            if isinstance(e, B):
                const_cmp(e.a)
                const_cmp(e.b)
            elif isinstance(e, U):
                const_cmp(e.a)
        for f in u.fns.values():
            for s in walk(f.body):
                for _, ex in exprs_of(s):
                    const_cmp(ex)
                if s.kind == 'assign' and s.var.k == 's' and s.var.i in statics:
                    x = s.e
                    if isinstance(x, C):
                        vals.add(x.v)
                    elif isinstance(x, U) and x.op == 'lnot':
                        vals.add(1)
                    elif isinstance(x, B) and x.op == 'add':
                        pass        # a counter: bounded by its comparison
                    else:
                        return full
        hi = max(vals)
        if hi >= len(u.pieces) or min(vals) < 0:
            return full
        return [(i, u.pieces[i]) for i in range(hi + 1) if u.pieces[i] in u.model]

    def piece_lines(self):
        e = self.e
        names = e.pieces
        out = []
        for i in range(0, len(names), 8):
            chunk = names[i:i + 8]
            # piece() wants the model's exact name: a few models keep capitals (COB matches case-insensitively, Lua does not)
            out.append(f'{", ".join(e.pname(n) for n in chunk)} = piece({", ".join(repr(e.u.model[n][1]) for n in chunk)})')
        return out

    def piece_query(self, n, head):
        u, e = self.u, self.e
        f = u.fns[n]
        e.cur = f
        slot = 0
        body = f.body
        # common shape: a single assignment of a constant
        simple = [s for s in body if s.kind != 'return']
        if len(simple) == 1 and simple[0].kind == 'assign' and simple[0].var.k == 'l' and simple[0].var.i == slot:
            return [head, f'\treturn {e.piece_value(simple[0].e)}', 'end']
        ret = lambda em, s, ind: [f'{ind}return piecenum']
        lines = self.fn_body(f, ret=ret, skip=[0])
        lines.insert(0, '\tlocal piecenum = -1')
        if not body or body[-1].kind != 'return':
            lines.append('\treturn piecenum')
        return [head] + lines + ['end']

    def fall_through_false(self, f):
        return [] if f.body and f.body[-1].kind == 'return' else ['\treturn false']

    def killed(self, n):
        u, e = self.u, self.e
        f = u.fns[n]

        def ret(em, s, ind):
            return [f'{ind}return corpsetype']
        lines = self.fn_body(f, ret=ret, skip=[0, 1])
        lines = inline_corpse(lines)
        # user decision: the worst a death leaves is the heap (engine: 1 = wreck, 2 = heap, 3 = nothing)
        lines = [re.sub(r'\b(return|corpsetype =) ([3-9])\b', r'\1 2', ln) for ln in lines]
        head = ['function script.Killed(recentDamage, maxHealth)', '\tlocal severity = recentDamage / maxHealth * 100']
        if any('corpsetype' in ln and 'return corpsetype' not in ln for ln in lines) or any('return corpsetype' in ln for ln in lines):
            head.append('\tlocal corpsetype = 0')
        tail = []
        if not f.body or f.body[-1].kind != 'return':
            tail = ['\treturn corpsetype']
        return head + lines + tail + ['end']

    def special_callins(self, out, block, internals):
        u, e, ci = self.u, self.e, self.ci

        def body_of(n, skip):
            if n in internals:
                raise Unsupported(f'{n} is called from the script')
            return self.fn_body(u.fns[n], ret=lambda em, s, ind: [f'{ind}return'], skip=skip)

        def threaded(n, lua, args, prelude, skip):
            """not thread-wrapped by the gadget"""
            lines = prelude + body_of(n, skip)
            if n in block:
                ln = u.fn_names[n]
                out.append([f'local function {ln}({args})'] + lines + ['end', '', f'function script.{lua}({args})', f'\tStartThread({ln}{", " + args if args else ""})', 'end'])
            else:
                out.append([f'function script.{lua}({args})'] + lines + ['end'])

        n = self.by_kind('hitbyweaponid')
        if n:
            raise Unsupported('HitByWeaponId')
        n = self.by_kind('hitbyweapon')
        if n:
            threaded(n, 'HitByWeapon', 'x, z', ['\tlocal anglex, anglez = 500 * z, 500 * x'], [0, 1])
        n = self.by_kind('rockunit')
        if n:
            out.append(['function script.RockUnit(x, z)', '\tlocal anglex, anglez = 500 * z, 500 * x'] + body_of(n, [0, 1]) + ['end'])
        n = self.by_kind('setsfxoccupy')
        if n:
            threaded(n, 'setSFXoccupy', 'terrain', [], [0])
        moverates = {k: n for n, (k, w) in ci.items() if k.startswith('moverate') and k != 'moverate'}
        if moverates:
            parts = []
            for k in sorted(moverates):
                n = moverates[k]
                ln = u.fn_names[n]
                if n not in internals:
                    parts.append([f'local function {ln}()'] + body_of(n, []) + ['end'])
            tab = ', '.join(f'[{k[-1]}] = {u.fn_names[moverates[k]]}' for k in sorted(moverates))
            anyblock = any(moverates[k] in block for k in moverates)
            call = 'StartThread(f)' if anyblock else 'f()'
            for p in parts:
                out.append(p)
            out.append([f'local MOVERATE = {{{tab}}}', 'function script.MoveRate(rate)', '\tlocal f = MOVERATE[rate]', f'\tif f then {call} end', 'end'])
        # wind generators and extractors
        ss, sd = self.by_kind('setspeed'), self.by_kind('setdirection')
        for k in (ss, sd):
            if k and k in internals:
                raise Unsupported(f'{k} is called from the script')
        if ss and ss in u.fns:
            ln = u.fn_names[ss]
            out.append([f'local function {ln}(speed)'] + self.fn_body(u.fns[ss], ret=lambda em, s, ind: [f'{ind}return'], skip=[0]) + ['end'])
        if sd and sd in u.fns:
            ln = u.fn_names[sd]
            out.append([f'local function {ln}(heading)'] + self.fn_body(u.fns[sd], ret=lambda em, s, ind: [f'{ind}return'], skip=[0]) + ['end'])
        if (ss and ss in block) or (sd and sd in block):
            raise Unsupported('SetSpeed/SetDirection can block')
        go = next((u.lname[k] for k in u.lname if k == 'go'), None)
        if self.ov.get('wind'):
            wind = ['function script.WindChanged(heading, strength)']
            if ss:
                wind.append(f'\t{u.fn_names[ss]}(floor(strength * 3000))')
                e.need.add('floor')
            if sd:
                wind.append(f'\t{u.fn_names[sd]}(heading)')
            wind.append('end')
            out.append(wind)
        if ss and self.ov.get('ext'):
            ext = ['function script.ExtractionRateChanged(rate)', f'\t{u.fn_names[ss]}(floor(rate * 500))']
            e.need.add('floor')
            if go:
                # COB: the engine also calls Go whenever the extractor is active
                ext += ['\tif GetUnitValue(COB.ACTIVATION) ~= 0 then', f'\t\t{"StartThread(" + u.fn_names[go] + ")" if go in block else u.fn_names[go] + "()"}', '\tend']
            ext.append('end')
            out.append(ext)
        # landing pads
        n = self.by_kind('querylandingpad')
        if n:
            f = u.fns[n]
            nm = [u.local_names[(n, i)] for i in range(f.nslots)]
            ret = lambda em, s, ind: [f'{ind}return {{{", ".join(nm)}}}']
            lines = self.fn_body(f, ret=ret, skip=range(f.nslots))
            head = ['function script.QueryLandingPads()'] + [f'\tlocal {x} = -1' for x in nm]
            tail = [] if f.body and f.body[-1].kind == 'return' else [f'\treturn {{{", ".join(nm)}}}']
            out.append(head + lines + tail + ['end'])
        # transports
        for k in ('begintransport', 'querytransport', 'transportpickup', 'transportdrop'):
            n = self.by_kind(k)
            if not n:
                continue
            f = u.fns[n]
            if k == 'querytransport':
                out.append(self.piece_query(n, 'function script.QueryTransport(unitid)'))
                for s in walk(f.body):
                    for _, ex in exprs_of(s):
                        for leaf in leaves(ex):
                            if isinstance(leaf, V) and leaf.k == 'l' and leaf.i == 1:
                                raise Unsupported('QueryTransport reads the model height, Lua gets a unit id')
            elif k == 'begintransport':
                lines = body_of(n, [0])
                head = 'function script.BeginTransport(unitid)'
                pre = []
                if any(isinstance(leaf, V) and leaf.k == 'l' and leaf.i == 0 for s in walk(f.body) for _, ex in exprs_of(s) for leaf in leaves(ex)):
                    pre = ['\tlocal height = floor(Spring.GetUnitHeight(unitid) * 65536)']
                    e.need.add('floor')
                out.append([head] + pre + lines + ['end'])
            elif k == 'transportpickup':
                out.append(['function script.TransportPickup(unitid)'] + body_of(n, [0]) + ['end'])
            elif k == 'transportdrop':
                pre = []
                if any(isinstance(leaf, V) and leaf.k == 'l' and leaf.i == 1 for s in walk(f.body) for _, ex in exprs_of(s) for leaf in leaves(ex)):
                    pre = ['\tlocal pos = floor(x) * 65536 + floor(z) % 65536   -- COB gets the drop point as PACKXZ']
                    e.need.add('floor')
                out.append(['function script.TransportDrop(unitid, x, y, z)'] + pre + body_of(n, [0, 1]) + ['end'])


def inline_corpse(lines):
    """`corpsetype = 3` directly followed (same block, no blocking between) by `return corpsetype` -> `return 3`"""
    out = list(lines)
    for i, ln in enumerate(out):
        m = re.match(r'^(\s*)return corpsetype$', ln)
        if not m:
            continue
        ind = m.group(1)
        for j in range(i - 1, -1, -1):
            lj = out[j]
            mj = re.match(r'^(\s*)corpsetype = (\S+)$', lj)
            if mj and mj.group(1) == ind:
                out[i] = f'{ind}return {mj.group(2)}'
                out[j] = None
                break
            if lj is None:
                continue
            if len(lj) - len(lj.lstrip('\t')) < len(ind):
                break
    return [x for x in out if x is not None]


# ---------------------------------------------------------------------------------------- driver

def find_ci(folder, name):
    for f in os.listdir(folder):
        if f.lower() == name.lower():
            return f
    return None


def body_hash(body):
    return hashlib.sha1(body.encode()).hexdigest()[:12]


def existing_state(path):
    """(generated?, hand-edited?)"""
    if not os.path.exists(path):
        return False, False
    t = open(path, encoding='latin-1').read()
    m = HEADER_RE.search(t)
    if GEN_TAG not in t or not m:
        return False, True
    body = t[m.end() + 1:]
    return True, body_hash(body) != m.group(1)


def set_def_script(stem):
    p = os.path.join(UNITS, stem + '.lua')
    t = open(p, encoding='latin-1', newline='').read()
    if re.search(r'^\s*script\s*=', t, re.M):
        return False
    nl = '\r\n' if '\r\n' in t else '\n'
    m = re.search(r'^(\s*)objectname\s*=.*?$', t, re.M)
    if not m:
        raise Unsupported('def has no objectname line')
    line = f'{m.group(1)}script = "{stem}.lua",'
    t2 = t[:m.end()].rstrip('\r') + nl + line + t[m.end():]
    open(p, 'w', encoding='latin-1', newline='').write(t2)
    return True


def all_stems():
    return sorted(f[:-4] for f in os.listdir(UNITS) if f.endswith('.lua'))


def convert(stem, write=True, force=False):
    """-> (status, warnings)"""
    if stem in HAND:
        return 'hand', []
    cf = find_ci(SCRIPTS, stem + '.cob')
    if not cf:
        return 'no-cob', []
    lf = find_ci(SCRIPTS, stem + '.lua')
    out = os.path.join(SCRIPTS, lf or (stem + '.lua'))
    generated, edited = existing_state(out)
    if lf and not generated:
        return 'lua-exists', []
    if generated and edited and not force:
        return 'edited-skip', []
    try:
        import cob2lus_patches as P
    except ImportError:
        P = None
    u, hdr, body = transpile(stem, os.path.join(SCRIPTS, cf))
    if P:
        try:
            body = P.apply(stem, body)
        except ValueError as ex:
            raise Unsupported(str(ex))
    text = '\n'.join(hdr) + '\n-- cob2lus body sha1: ' + body_hash(body) + '\n' + body
    if write:
        open(out, 'w', encoding='latin-1', newline='\n').write(text)
        set_def_script(stem)
    else:
        print(text)
    return 'ok', u.warnings


def main(argv):
    force = '--force' in argv
    check = '--check' in argv
    argv = [a for a in argv if a not in ('--force', '--check')]
    if '--all' in argv:
        stems = [s for s in all_stems() if s not in HAND]
    else:
        stems = argv
    failed, warned, done, skipped = [], {}, [], []
    for stem in stems:
        try:
            st, w = convert(stem, write=not check, force=force)
        except Unsupported as ex:
            failed.append((stem, str(ex)))
            continue
        if st == 'ok':
            done.append(stem)
            if w:
                warned[stem] = w
        elif st != 'lua-exists' and st != 'no-cob':
            skipped.append((stem, st))
    print(f'converted {len(done)}, failed {len(failed)}, skipped {len(skipped)}')
    for s, st in skipped:
        print(f'  skipped {s}: {st}')
    for s, w in sorted(warned.items()):
        for x in dict.fromkeys(w):
            print(f'  warning {s}: {x}')
    for s, m in failed:
        print(f'  FAILED {s}: {m}')
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
