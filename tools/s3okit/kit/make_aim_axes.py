#!/usr/bin/env python3
"""Barrel axes for tools/headless-test zz_walker_aim_probe: for every empty piece (muzzle) in objects3d/*.s3o, its first ancestor with geometry and
the direction from that geometry's centre to the muzzle, in the ancestor's local frame. Writes tools/headless-test/tartest.sdd/luarules/aim_axes.lua."""
import glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from s3okit import s3o
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
out = ['-- generated by tools/s3okit/kit/make_aim_axes.py', 'return {']
for f in sorted(glob.glob(os.path.join(ROOT, 'objects3d', '*.s3o'))):
    try:
        P = {p['name']: p for p in s3o.read(f)['pieces']}
    except Exception:
        continue
    rows = []
    for n, p in P.items():
        if p['idx'] or not p['parent']:
            continue
        ox, oy, oz = p['off']; a = p['parent']
        while a and not P[a]['idx']:
            q = P[a]; ox += q['off'][0]; oy += q['off'][1]; oz += q['off'][2]; a = q['parent']
        if not a:
            continue
        idx = P[a]['idx']; V = P[a]['verts']
        c = [sum(V[i][k] for i in idx) / len(idx) for k in range(3)]
        rows.append('["%s"]={"%s",%.3f,%.3f,%.3f,%.3f,%.3f,%.3f}' % (n, a, ox - c[0], oy - c[1], oz - c[2], ox, oy, oz))
    if rows:
        out.append('["%s"]={%s},' % (os.path.basename(f)[:-4].lower(), ','.join(rows)))
out.append('}')
open(os.path.join(ROOT, 'tools/headless-test/tartest.sdd/luarules/aim_axes.lua'), 'w').write('\n'.join(out) + '\n')
