--  Documents
--------------------------------------------------------------------------------

-- Every document this widget has loaded, so the theme can be re-applied to
-- them when the player changes the tint or opacity.
local documents = {}

-- The stylesheet rules the player's settings add on top of theme.rcss: the
-- panel colour and opacity, the tint. Generated by the Slate Core widget.
local function ThemeRules()
	local S = WG.Slate
	if S and S.ThemeRules then
		return S.ThemeRules()
	end
	return nil
end

-- Recoil's Document:AppendToStyleSheet builds the new sheet with the appended
-- rules as the base and the document's own rules merged on top, so on equal
-- specificity the file's rule wins, not the appended one. The theme's rules
-- therefore need more specificity than anything in theme.rcss or a
-- document's own <style>: every document body gets this id, and each
-- generated rule is scoped under it (an id outweighs any number of classes).
local THEME_ID = "slate-themed"

local function ApplyTheme(document)
	local rules = ThemeRules()
	if not (rules and rules ~= "" and document.AppendToStyleSheet) then
		return
	end
	pcall(function() document.id = THEME_ID end)
	-- "a, b { ... }" becomes "#id a, #id b { ... }"
	local scoped = rules:gsub("([^\n{]+)(%s*{)", function(selectors, brace)
		local parts = {}
		for selector in selectors:gmatch("[^,]+") do
			parts[#parts + 1] = "#" .. THEME_ID .. " " .. selector:match("^%s*(.-)%s*$")
		end
		return table.concat(parts, ", ") .. brace
	end)
	pcall(document.AppendToStyleSheet, document, scoped)
end

-- Loads a document into the shared context, with the fonts in place first so
-- its text is laid out with them, and the player's theme on top of the
-- stylesheet. `path` is relative to luaui/slate/rml/. Returns the document, or
-- nil and a reason.
function hud.LoadDocument(path, widget)
	if not RmlUi then
		return nil, "RmlUi is not available"
	end
	local context = hud.UpdateScale()
	if not context then
		return nil, "no RmlUi context"
	end
	hud.LoadFonts()
	local full = hud.RML_DIR .. path
	local ok, result = pcall(context.LoadDocument, context, full, widget)
	if not ok or not result then
		return nil, "could not load " .. full .. (ok and "" or (": " .. tostring(result)))
	end
	ApplyTheme(result)
	documents[#documents + 1] = result
	return result
end

-- Closes a document loaded with hud.LoadDocument.
function hud.CloseDocument(document)
	if not document then
		return
	end
	for i = #documents, 1, -1 do
		if documents[i] == document then
			table.remove(documents, i)
		end
	end
	pcall(document.Close, document)
end

-- Re-reads theme.rcss and puts the player's theme back on top, for every
-- document this widget has open. The Slate Core widget calls this through
-- the widget's change listener when a setting changes.
function hud.Restyle()
	for _, document in ipairs(documents) do
		if document.ReloadStyleSheet then
			pcall(document.ReloadStyleSheet, document)
		end
		ApplyTheme(document)
	end
end

-- Registers fn to run whenever a Slate setting changes (opacity, tint, scale,
-- panel positions reset...). Documents are restyled first, so fn only has to
-- re-place its panels. `owner` is a unique string (the widget's name).
function hud.OnChange(owner, fn)
	local S = WG.Slate
	if S and S.OnChange then
		S.OnChange(owner, function()
			hud.Restyle()
			if fn then
				fn()
			end
		end)
	end
end

function hud.OffChange(owner)
	local S = WG.Slate
	if S and S.OffChange then
		S.OffChange(owner)
	end
end

-- Shows a document without giving it keyboard focus, so a passive HUD panel
-- never swallows key presses.
function hud.ShowPassive(document)
	if RmlUi.RmlModalFlag and RmlUi.RmlFocusFlag then
		document:Show(RmlUi.RmlModalFlag.None, RmlUi.RmlFocusFlag.None)
	else
		document:Show()
	end
end

--------------------------------------------------------------------------------
--  Sounds: the game names them in slate_game.lua (sounds = {click=, hover=,
--  ...}); a name that is not there plays nothing.
--------------------------------------------------------------------------------

function hud.Sound(name, volume)
	local S = WG.Slate
	local sounds = S and S.game and S.game.sounds
	local file = sounds and sounds[name]
	if file and file ~= "" then
		Spring.PlaySoundFile(file, volume or 1.0, "ui")
	end
end

--------------------------------------------------------------------------------
--  Panel placement
--
--  A panel is an absolutely positioned element of a known size in dp. Its
--  position is its default spot unless the player has dragged it in tweak
--  mode (Ctrl+F11), which is handled by slate_api_layout.lua (WG.SlateLayout).
--
--  defaultOrigin(vsx, vsy, w, h, scale) returns the default bottom-left
--  corner in screen pixels (y counts up from the bottom, as everywhere in
--  LuaUI). RmlUi counts y down from the top; the conversion happens here.
--------------------------------------------------------------------------------

function hud.PlacePanel(element, name, widthDp, heightDp, defaultOrigin)
	if not element then
		return
	end
	local vsx, vsy = Spring.GetViewGeometry()
	local scale = hud.GetScale()
	local w = math.floor(widthDp * scale + 0.5)
	local h = math.floor(heightDp * scale + 0.5)
	local x1, y1 = defaultOrigin(vsx, vsy, w, h, scale)
	x1, y1 = math.floor(x1), math.floor(y1)
	local layout = WG.SlateLayout
	if layout and layout.Place then
		x1, y1 = layout.Place(name, x1, y1, w, h)
	end
	element.style["left"] = string.format("%dpx", x1)
	element.style["top"] = string.format("%dpx", vsy - (y1 + h))
	return x1, y1, w, h
end

-- The gap between a panel and the screen edge, and between stacked panels,
-- in dp (from slate_theme.lua).
function hud.Margin()
	local S = WG.Slate
	return (S and S.theme and S.theme.margin) or 16
end

function hud.Gap()
	local S = WG.Slate
	return (S and S.theme and S.theme.gap) or 16
end

-- Registers a panel with tweak mode. onMove is called after the player drops
-- the panel somewhere new; it should call hud.PlacePanel again. isVisible
-- (optional) says whether the panel is on screen at the moment: a window that
-- is closed should not be offered for dragging.
function hud.RegisterPanel(name, label, onMove, isVisible)
	local layout = WG.SlateLayout
	if layout and layout.Register then
		layout.Register(name, {label = label, onMove = onMove, isVisible = isVisible})
		return true
	end
	return false
end

function hud.UnregisterPanel(name)
	local layout = WG.SlateLayout
	if layout and layout.Unregister then
		layout.Unregister(name)
	end
end

--------------------------------------------------------------------------------
--  Team colors
--------------------------------------------------------------------------------

-- A team color as text on the dark panels. A color too dark to read is made
-- brighter: first by scaling it up (which keeps its hue and saturation), then
-- by mixing in white. Takes r, g, b in 0..1 and returns an RCSS color.
local MIN_LUMINANCE = 0.45

local function Luminance(r, g, b)
	return 0.2126 * r + 0.7152 * g + 0.0722 * b
end

function hud.ReadableColor(r, g, b)
	r, g, b = r or 1, g or 1, b or 1
	if Luminance(r, g, b) < MIN_LUMINANCE then
		local peak = math.max(r, g, b)
		if peak > 0.001 then
			r, g, b = r / peak, g / peak, b / peak
		else
			r, g, b = 0.5, 0.5, 0.5 -- a black team color: fall back to grey
		end
		local luminance = Luminance(r, g, b)
		if luminance < MIN_LUMINANCE then
			local t = (MIN_LUMINANCE - luminance) / (1 - luminance)
			r = r + (1 - r) * t
			g = g + (1 - g) * t
			b = b + (1 - b) * t
		end
	end
	return string.format("rgb(%d,%d,%d)", math.floor(r * 255 + 0.5), math.floor(g * 255 + 0.5), math.floor(b * 255 + 0.5))
end

-- a color exactly as given, for swatches and bars
function hud.Rgb(r, g, b)
	return string.format("rgb(%d,%d,%d)", math.floor((r or 1) * 255 + 0.5), math.floor((g or 1) * 255 + 0.5), math.floor((b or 1) * 255 + 0.5))
end

-- a {r, g, b, a} theme colour as RCSS (alpha 0-1 becomes 0-255)
function hud.Rgba(c, alpha)
	alpha = alpha or c[4] or 1
	return string.format("rgba(%d,%d,%d,%d)",
		math.floor((c[1] or 1) * 255 + 0.5), math.floor((c[2] or 1) * 255 + 0.5),
		math.floor((c[3] or 1) * 255 + 0.5), math.floor(alpha * 255 + 0.5))
end

