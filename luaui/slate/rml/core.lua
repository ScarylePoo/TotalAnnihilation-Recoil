--------------------------------------------------------------------------------
--  Shared helpers for the Slate RmlUi widgets. Load with
--  include("slate/rml/core.lua").
--
--  Every widget gets its own copy of this module (include runs the file each
--  time), so module-level state here is per widget. Anything that must be
--  shared between widgets lives in WG.Slate, which the Slate Core widget
--  (slate_api_core.lua) publishes: the theme, the game config, the player's
--  settings and the colour tint.
--
--  Derived from LuaUI/rml/hud.lua in Splinter Faction (same author, GPL v2+).
--------------------------------------------------------------------------------

local hud = {}

local CONTEXT_NAME = "slate"

hud.DIR = LUAUI_DIRNAME .. "slate/"
hud.RML_DIR = hud.DIR .. "rml/"
hud.IMAGE_DIR = hud.DIR .. "images/"

-- The HUD is laid out in "dp" for a 1920x1080 screen and scaled from there.
local BASE_WIDTH = 1920
local BASE_HEIGHT = 1080

-- Saira SemiCondensed is the Slate typeface. RmlUi names a face by the family
-- name stored in the file, and both files register as "Saira SemiCondensed":
-- SemiBold as weight 600 (what "font-weight: normal" picks, being the closest)
-- and Bold as weight 700. The first face is also the fallback for glyphs
-- missing elsewhere; a fallback does not cover a family name that does not
-- exist, which draws no text at all.
local FONT_FILES = {
	hud.DIR .. "fonts/Saira_SemiCondensed-SemiBold.ttf",
	hud.DIR .. "fonts/Saira_SemiCondensed-Bold.ttf",
}

-- Loads the fonts once per LuaUI session (WG is shared by all widgets).
-- Returns true when every face is available.
function hud.LoadFonts()
	if WG.slateFonts ~= nil then
		return WG.slateFonts
	end
	local allLoaded = true
	for i, path in ipairs(FONT_FILES) do
		local ok, loaded = pcall(RmlUi.LoadFontFace, path, i == 1)
		if not ok or loaded == false then
			allLoaded = false
			Spring.Echo("[Slate] could not load font " .. path .. (ok and "" or (": " .. tostring(loaded))))
		end
	end
	WG.slateFonts = allLoaded
	return allLoaded
end

-- The context every Slate document lives in.
function hud.GetContext()
	local context = RmlUi.GetContext(CONTEXT_NAME)
	if not context then
		context = RmlUi.CreateContext(CONTEXT_NAME)
	end
	return context
end

-- The shared state from the Slate Core widget, or nil when it is not running.
function hud.Slate()
	return WG.Slate
end

-- Pixels per dp: the resolution relative to 1080p, times the player's
-- interface size setting.
function hud.GetScale()
	local vsx, vsy = Spring.GetViewGeometry()
	local userScale = WG.Slate and WG.Slate.Get and WG.Slate.Get("scale") or 1
	if not userScale or userScale <= 0 then
		userScale = 1
	end
	local scale = math.min(vsx / BASE_WIDTH, vsy / BASE_HEIGHT) * userScale
	scale = math.floor(scale * 100 + 0.5) / 100
	if scale < 0.5 then
		scale = 0.5
	end
	return scale
end

-- Call when a widget starts and whenever the view is resized.
function hud.UpdateScale()
	local context = hud.GetContext()
	if context then
		local scale = hud.GetScale()
		if context.dp_ratio ~= scale then
			context.dp_ratio = scale
		end
	end
	return context
end

