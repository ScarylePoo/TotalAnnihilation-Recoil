-- Commanders: read by luarules/gadgets/game_com_ends.lua (game end modes
-- "commander" and "comends"). Decoy commanders are deliberately not listed.
local COMMANDERS = {
	arm_commander  = true,
	core_commander = true,
}

function UnitDef_Post(name, ud)
	-- TA units did not regenerate; the engine's default is 10 HP/s after idleTime. Units without the tag get none.
	if ud.idleautoheal == nil then
		ud.idleautoheal = 0
	end
	if COMMANDERS[name] then
		ud.customparams = ud.customparams or {}
		ud.customparams.iscommander = 1
	end
	-- Movement modoptions (modoptions.lua, both on unless set to 0): ground units (land, sea, hover; not aircraft,
	-- whose flight model reads speed and acceleration differently) get 1.5x TA's top speed, and accelerate at least
	-- at 1 elmo/frame^2. brakeRate and turnRate stay TA's. The walk animations (scripts/headers/walk.lua) step at
	-- UnitDefs speed, so legs keep pace.
	local mo = Spring.GetModOptions and Spring.GetModOptions() or {}
	local function optOn(key) return mo[key] == nil or tobool(mo[key]) end
	local speed = tonumber(ud.maxvelocity or ud.speed)
	if speed and speed > 0 and not tobool(ud.canfly) then
		if optOn("fastunits") then
			-- whichever the def gives: maxvelocity (elmos/frame) or speed (elmos/s)
			if ud.maxvelocity then ud.maxvelocity = tonumber(ud.maxvelocity) * 1.5 end
			if ud.speed then ud.speed = tonumber(ud.speed) * 1.5 end
		end
		if optOn("quickacceleration") then
			ud.acceleration = math.max(tonumber(ud.acceleration) or 0, 1)
		end
	end
	-- Armed planes (fighters, bombers: Recoil's "strafing" aircraft) ignore "acceleration" and read only "maxAcc",
	-- defaulting to 0.065 for all of them (engine UnitDef.cpp). And their thrust works against a drag that grows with
	-- speed (StrafeAirMoveType: drag = maxAcc / (1.1 x maxSpeed)), so they approach top speed instead of reaching it:
	-- 90 % takes ~1.9 x speed/maxAcc in theory, where TA's linear acceleration takes 0.9 x speed/acceleration; they
	-- also fly part-throttle. Measured (tools/headless-test FLIGHT=1, from the move order, takeoff included), 3 x TA's
	-- value gives TA's time to 90 % of top speed: bombers within a few frames, fighters ~0.4 s over (the takeoff).
	-- Unarmed planes (Peeper, Fink, Eagle...) read "acceleration" but fly the same drag model, so they get it too.
	-- Their brakeRate is used only when landing.
	if ud.canfly and ud.maxacc == nil and ud.acceleration and not (ud.hoverattack or (tonumber(ud.workertime) or 0) > 0
			or (tonumber(ud.transportcapacity) or 0) > 0) then
		ud.maxacc = 3 * ud.acceleration
	end
	-- Normal map for CUS GL4 (BAR's reads customParams.normaltex for units; features find theirs by the same naming,
	-- <tex1>_normals.dds). Generated by tools/textures/normalmaps.py; every unit's tex1 is <model>_1.dds.
	local stem = ud.objectname and ud.objectname:match("([^/\\]+)%.[sS]3[oO]$")
	if stem then
		local normaltex = "unittextures/" .. stem .. "_1_normals.dds"
		if VFS.FileExists(normaltex) then
			ud.customparams = ud.customparams or {}
			ud.customparams.normaltex = normaltex
		end
	end
	-- Flying debris (pieces thrown by Explode() in the death scripts) trails Splinter Faction's fire and smoke
	-- (gamedata/explosions/deathceg.lua).
	ud.sfxtypes = ud.sfxtypes or {}
	ud.sfxtypes.pieceexplosiongenerators = { "deathceg3", "deathceg4" }
	-- Mexes: metal makers in disguise on fixed metal spots (luarules/gadgets/game_metal_spots.lua and
	-- game_metal_spot_output.lua). No extraction; building mask 4, so they can only be built on spots (and nothing
	-- else can); output = the spot value x metal_spot_mult (moho 3x, TA's ratio); TA's energy use as upkeep while on.
	-- Moho mines stack (yardmap "s") so they can be placed over a basic mex, which vanishes when the moho finishes
	-- (unit_mex_upgrade.lua). customparams.metal_extractor: Splinter Faction's placement widget looks for it.
	local mexMult = name:find("_mohomine$") and 3 or (name:find("metalextractor$") and 1 or nil)   -- incl. underwater
	if mexMult then
		ud.customparams = ud.customparams or {}
		ud.customparams.metal_extractor = 1
		ud.customparams.metal_spot_mult = mexMult
		ud.customparams.mex_energy = tonumber(ud.energyuse) or 0
		ud.energyuse = 0
		ud.extractsmetal = 0
		ud.buildingmask = 4
		ud.onoffable = true
		ud.activatewhenbuilt = true
		if mexMult > 1 then
			local fx, fz = tonumber(ud.footprintx) or 5, tonumber(ud.footprintz) or 5
			local row = string.rep("s", fx)
			local rows = {}
			for i = 1, fz do rows[i] = row end
			ud.yardmap = table.concat(rows, " ")
		end
	end
	-- Air repair pads: the engine ignores isairbase, luarules/gadgets/unit_air_pads.lua reads this.
	if ud.isairbase then
		ud.customparams = ud.customparams or {}
		ud.customparams.isairbase = 1
	end
end

