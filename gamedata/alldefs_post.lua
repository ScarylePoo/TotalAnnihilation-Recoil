-- Plasma balls: every Cannon is the engine's default orange (BOTA had tinted some).
local PLASMA_ORANGE = "1.0 0.5 0.0"

local function MaxDamage(wd)
	local d = 0
	for _, v in pairs(wd.damage or {}) do d = math.max(d, tonumber(v) or 0) end
	return d
end

local function Faction(name)
	if name:sub(1, 3) == "arm" then return "arm" end
	if name:sub(1, 3) == "cor" then return "core" end
end

-- dominant colour of a laser, for a matching impact
local function LaserColor(wd)
	local r, g, b = tostring(wd.rgbcolor or ""):match("([%d%.]+)%s+([%d%.]+)%s+([%d%.]+)")
	r, g, b = tonumber(r) or 1, tonumber(g) or 0, tonumber(b) or 0
	if r > 0.4 and b > 0.4 and g < 0.4 then return "purple" end
	if g >= r and g >= b then return "green" end
	if b >= r and b >= g then return "blue" end
	if g > 0.35 then return "orange" end
	return "red"
end

-- Anti-air: TA gave these a damage bonus against aircraft (gamedata/ArmorDefs.lua *_aircraft classes), or they cannot
-- shoot the ground.
local function IsAntiAir(wd)
	if wd.canattackground == false or wd.canattackground == 0 then return true end
	local air, ground = 0, 0
	for k, v in pairs(wd.damage or {}) do
		v = tonumber(v) or 0
		if k:find("aircraft") then air = math.max(air, v) else ground = math.max(ground, v) end
	end
	return air > ground * 1.2   -- the Neutron hits Arm aircraft and Arm ground units alike: not AA
end

local function Reload(wd) return tonumber(wd.reloadtime) or 1 end

-- Impact effect for every weapon (user's rules, 2026-11-07):
--   lasers: a black scorch with a small burn (burnblacksmall); only very heavy lasers (>= 1000 damage: Annihilator,
--     Doomsday, Penetrator, Krogoth, sniper) get a shell explosion in their own colour
--   light, fast-firing plasma (E.M.G.s of the Flash, Peewee, Warrior...): burnblacksmall
--   everything else: genericshellexplosion-<size>-<colour>; cannons orange, anti-air purple, ground missiles red
--   D-Gun: small orange on each hit
local function ImpactCEG(name, wd)
	local t, d, aoe = wd.weapontype, MaxDamage(wd), tonumber(wd.areaofeffect) or 0
	local size = (d < 150 and aoe < 48) and "small" or ((d < 500 and aoe < 120) and "medium" or "large")
	if wd.interceptor and tobool(wd.interceptor) then return "genericshellexplosion-large-white" end
	if wd.paralyzer and tobool(wd.paralyzer) then
		return aoe >= 200 and "genericbuildingexplosion-huge-blue-emp" or "genericshellexplosion-electric-small"
	end
	if t == "DGun" or name == "disintegrator" then   -- the D-Gun def has no weapontype (the engine finds it by name)
		return "genericshellexplosion-small-orange"
	elseif t == "LaserCannon" or t == "BeamLaser" then
		if d >= 1000 then return "genericshellexplosion-large-" .. LaserColor(wd) end
		return "burnblacksmall"
	elseif t == "Cannon" then
		local d0 = tonumber((wd.damage or {}).default) or d   -- default damage: the Immolator's 200 vs Flash is a bonus
		if d0 < 25 and Reload(wd) <= 1 then return "burnblacksmall" end            -- E.M.G.s, Immolator
		if IsAntiAir(wd) then return "genericshellexplosion-" .. (size == "large" and "medium" or size) .. "-purple" end   -- flak
		return "genericshellexplosion-" .. size .. "-orange"
	elseif t == "MissileLauncher" or t == "StarburstLauncher" then
		if t == "StarburstLauncher" and d >= 2500 then return aoe >= 700 and "nukedatbewm" or "nukedatbewmsmall" end
		if IsAntiAir(wd) then return "genericshellexplosion-" .. (size == "large" and "medium" or size) .. "-purple" end
		return "genericshellexplosion-" .. size .. "-red"
	elseif t == "TorpedoLauncher" then
		return "torpedoexplosion"
	elseif t == "AircraftBomb" then
		return (d >= 500 or aoe >= 150) and "genericshellexplosion-bomb-huge" or "genericshellexplosion-bomb"
	elseif t == "LightningCannon" then
		return "genericshellexplosion-electric-small"
	elseif t == "Flame" then
		return "burnblacksmall"
	end
	return "genericshellexplosion-" .. size .. "-orange"
end

-- Muzzle flash (luarules/gadgets/fx_muzzle.lua spawns it where the shot leaves the barrel;
-- gamedata/explosions/tar-muzzleflashes.lua): plasma cannons Splinter Faction's gdhcannon flame, energy weapons
-- (lasers, lightning, D-Gun) its electricity flash with a ring in the weapon's colour; sized by the weapon.
-- Missiles, bombs, torpedoes and flamethrowers have none.
local function MuzzleCEG(name, wd)
	local t = wd.weapontype
	local d0 = tonumber((wd.damage or {}).default) or MaxDamage(wd)
	local d = math.max(d0, math.min(MaxDamage(wd), d0 * 4))   -- one-sided weapons (Neutron, Stunner) count a bit more
	local function sz(cuts)
		for i = 1, #cuts do if d < cuts[i] then return ({ "tiny", "small", "medium", "large" })[i] end end
		return "huge"
	end
	if t == "DGun" or name == "disintegrator" then
		return "tar-muzzle-energy-large-orange"
	elseif t == "Cannon" then
		local r = sz({ 25, 90, 250, 900 })
		local down = { huge = "large", large = "medium", medium = "small", small = "tiny", tiny = "tiny" }
		if Reload(wd) < 1 then r = down[r] end   -- rapid fire (Vulcan, Buzzsaw, flak, Maverick): one size smaller
		return "tar-muzzle-cannon-" .. r
	elseif t == "LaserCannon" or t == "BeamLaser" then
		local colour = (wd.paralyzer and tobool(wd.paralyzer)) and "blue" or LaserColor(wd)
		return "tar-muzzle-energy-" .. sz({ 25, 100, 250, 1000 }) .. "-" .. colour
	elseif t == "LightningCannon" then
		return "tar-muzzle-energy-medium-blue"
	end
end

-- Death explosions: TA's explosion weapon (damage, area) stays; the effect is chosen per unit (size from the unit,
-- colour from what it is). DeathExplosions() clones the weapon per effect ("<weapon>__<effect>") and repoints units.
local SIZES = { "small", "medium", "large", "huge" }
local function UnitSizeLevel(ud, mobile)
	local fp = math.max(tonumber(ud.footprintx) or 1, tonumber(ud.footprintz) or 1)
	local cost = tonumber(ud.buildcostmetal) or 0
	local lvl
	if mobile then
		lvl = cost < 150 and 1 or cost < 600 and 2 or cost < 4000 and 3 or 4
		-- wide hulls (ships, hovers) at least medium / large; a 4x4 patrol boat is not a large blast
		if fp >= 6 then lvl = math.max(lvl, 3) elseif fp >= 4 then lvl = math.max(lvl, 2) end
	else
		lvl = fp <= 2 and 1 or fp <= 4 and 2 or fp <= 6 and 3 or 4
		if cost < 200 then lvl = math.min(lvl, 2) end   -- cheap but wide (solar collectors): at most medium
		if cost >= 8000 then lvl = 4 end
	end
	return lvl
end

-- name keyword -> building explosion colour (first match wins); "-emp" adds the electric shockwave
local BUILDING_COLORS = {
	{ "fusion", "white-emp", 4 }, { "geothermal", "orange-emp" },
	{ "energystorage", "blue-emp" }, { "solar", "blue-emp" }, { "wind", "blue-emp" }, { "tidal", "blue-emp" },
	{ "metal", "green" }, { "moho", "green" },
	{ "radar", "purple" }, { "sonar", "purple" }, { "targeting", "purple" },
	{ "retaliator", "white-emp" }, { "silencer", "white-emp" }, { "neutron", "white-emp" }, { "stunner", "blue-emp" },
	{ "protector", "white" }, { "fortitude", "white" },
	{ "_lab_", "orange" }, { "plant", "orange" }, { "shipyard", "orange" }, { "gantry", "orange" }, { "repairpad", "orange" },
	{ "_def_", "red" }, { "_seadef_", "red" },
}

local function DeathCEG(uname, ud, selfd)
	local mobile = (tonumber(ud.maxvelocity) or 0) > 0 or tobool(ud.canfly)
	local lvl = UnitSizeLevel(ud, mobile)
	if selfd then lvl = math.min(lvl + 1, 4) end
	if uname:find("decoycommander") then return "genericunitexplosion-large-white" end
	if uname:find("commander") then return "nukedatbewmsmall" end
	if uname:find("krogoth") and mobile then return "genericunitexplosion-huge-purple" end
	if uname:find("_mine6") then return "nukedatbewmsmall" end
	if uname:find("_mine%d") then return "genericbuildingexplosion-" .. SIZES[math.min(lvl + 1, 4)] .. "-red-emp" end
	if uname:find("geothermal") and selfd then return "nukedatbewmsmall" end   -- TA: a geothermal self-destructs like a nuke
	if not mobile then
		for _, rule in ipairs(BUILDING_COLORS) do
			if uname:find(rule[1], 1, true) then
				return "genericbuildingexplosion-" .. SIZES[math.max(lvl, rule[3] or 1)] .. "-" .. rule[2]
			end
		end
		return "genericbuildingexplosion-" .. SIZES[lvl] .. "-orange"
	end
	local color
	if uname:find("_air_") or uname:find("_seapl_") then
		color = "white"                                   -- aircraft: bright air bursts
	elseif uname:find("_sea_") then
		color = "orange"                                  -- ships burn
	else
		color = (Faction(uname) == "core") and "red" or "blue"
	end
	return "genericunitexplosion-" .. SIZES[lvl] .. "-" .. color
end

function DeathExplosions(UnitDefs, WeaponDefs)
	local made = {}
	for uname, ud in pairs(UnitDefs) do
		for _, slot in ipairs({ "explodeas", "selfdestructas" }) do
			local base = ud[slot] and tostring(ud[slot]):lower()
			if base and WeaponDefs[base] then
				local ceg = DeathCEG(uname, ud, slot == "selfdestructas")
				local variant = base .. "__" .. ceg
				if not made[variant] then
					local wd = table.copy(WeaponDefs[base])
					wd.explosiongenerator = "custom:" .. ceg
					wd.customparams = wd.customparams or {}
					wd.customparams.deathexplosion = ceg
					WeaponDefs[variant] = wd
					made[variant] = true
				end
				ud[slot] = variant
			end
		end
	end
end

function WeaponDef_Post(name, weaponDef)
	for i = 1, #TA_ONLY_TAGS do weaponDef[TA_ONLY_TAGS[i]] = nil end

	
	weaponDef.soundhitwet = ""
	if weaponDef.range and tonumber(weaponDef.range) < 550 or 
		weaponDef.reloadtime and tonumber(weaponDef.reloadtime)<1.5 or
		explosiveWeapons[weaponDef.weapontype] then
			weaponDef.avoidfeature = false	-- don't avoid features if short range, explosive or rapid fire weapon
	end
	if explosiveWeapons[weaponDef.weapontype] then
		-- (BOTA widened the area of effect of every explosive weapon with an edgeeffectiveness here; TA's AoE is used as is.)
		if weaponDef.weapontype == "Cannon" then
			weaponDef.size = CannonSize(weaponDef)
		end
		if weaponDef.weapontype == "Cannon" and weaponDef.range and not weaponDef.mygravity and not weaponDef.cylindertargeting and name:find("armsfig_weapon") == nil then -- exclude arm tornado weapon, because it fires cannon weapon type from the air down on land
			weaponDef.mygravity = TA_GRAVITY
			weaponDef.gravityaffected = true
		elseif weaponDef.interceptor then
			weaponDef.interceptor = interceptorStyle
		end
		if weaponDef.weapontype == "TorpedoLauncher" then
			weaponDef.soundhitwet = weaponDef.soundhitdry
			-- A dropped torpedo enters the water at plane speed (~11 elmos/frame, 3x its rated speed) and the engine never slows it,
			-- while it turns a fixed angle per frame: it needs 75 elmos (turnrate 15000) to over 150 (10000) to level off, and
			-- blows up on any shallower seabed. Touching the seabed instead sheds the excess speed and lets it steer on.
			weaponDef.groundbounce = true
			weaponDef.bouncerebound = 0.2
			weaponDef.bounceslip = 0.3
			weaponDef.numbounce = 2
		else
			local AoE = tonumber(weaponDef.areaofeffect) or 0
			if AoE<50 then
				weaponDef.soundhitwet = "splshbig"
			elseif AoE<88 then
				weaponDef.soundhitwet = "splssml"
			elseif AoE<145 then
				weaponDef.soundhitwet = "splsmed"
			elseif AoE>450 then
				weaponDef.soundhitwet = weaponDef.soundhitdry
			else
				weaponDef.soundhitwet = "splslrg"
			end
		end
	elseif inertialessWeapons[weaponDef.weapontype] then
		if weaponDef.weapontype == "LaserCannon" then
			LaserLook(weaponDef)
		end
		weaponDef.impulseboost = 0
		weaponDef.impulsefactor = 0
		weaponDef.soundhitwet = "sizzle"		
		if weaponDef.weapontype == "LaserCannon" or weaponDef.weapontype == "EmgCannon" then
			weaponDef.cegtag = ""	-- we use the projectile lights widget now
		elseif weaponDef.weapontype == "BeamLaser" then
			weaponDef.soundhitdry = ""
			weaponDef.soundtrigger = 1
			--weaponDef.sweepfire = 0	-- at least till test phase of spring is over
		elseif weaponDef.weapontype == "DGun" then
			weaponDef.waterweapon = true	-- make DGun ball pierce water, but don't allow firing while under water
			weaponDef.firesubmersed = false
			weaponDef.avoidFriendly = false	-- make DGun ball shoot through anything, anywhere, anytime
			weaponDef.avoidFeature = false
			weaponDef.avoidGround = false
			weaponDef.avoidNeutral = false
		end
	end	
	if weaponDef.cratermult then 
		weaponDef.cratermult = weaponDef.cratermult * 0.4
	else
		weaponDef.cratermult = 0.4
	end
	if weaponDef.craterboost then
		weaponDef.craterboost = weaponDef.craterboost * 0.4
	else
		weaponDef.craterboost = 0
	end

	if weaponDef.weapontype == "Cannon" then
		CannonTrail(weaponDef)
		weaponDef.rgbcolor = PLASMA_ORANGE
	end

	-- an impact effect on every weapon (TA-era effect names are gone with the old effect library)
	local impact = ImpactCEG(name, weaponDef)
	weaponDef.explosiongenerator = "custom:" .. impact
	weaponDef.customparams = weaponDef.customparams or {}
	weaponDef.customparams.impactceg = impact   -- readable from Lua (WeaponDefs[id].customParams.impactceg)
	weaponDef.customparams.muzzleceg = MuzzleCEG(name, weaponDef)   -- spawned by luarules/gadgets/fx_muzzle.lua

	-- Don't collide with friendlies (modoption)
	if modOptions.nocollide and tobool(modOptions.nocollide) then
		weaponDef.collidefriendly = false
	end
end
