--------------------------------------------------------------------------------
-- TA:Recoil: normal maps for CUS GL4 (luarules/gadgets/cus_gl4.lua reads customParams.normaltex; without it a
-- feature gets the blank normal map). Generated by tools/textures/normalmaps.py as <tex1 stem>_normals.dds; every
-- feature model's tex1 is <model>_1.dds (wrecks, heaps, dragon's teeth, walls).
for _, fd in pairs(FeatureDefs) do
	local stem = type(fd) == "table" and type(fd.object) == "string" and fd.object:match("([^/\\]+)%.[sS]3[oO]$")
	if stem then
		local normaltex = "unittextures/" .. stem .. "_1_normals.dds"
		if VFS.FileExists(normaltex) then
			fd.customparams = fd.customparams or {}
			fd.customparams.normaltex = normaltex
		end
	end
end
